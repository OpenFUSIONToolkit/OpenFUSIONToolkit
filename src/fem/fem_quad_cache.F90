!> @file fem_quad_cache.F90
!
!> Precomputed basis and geometry data at quadrature points for 3D FE kernels
!!
!! Two objects are provided:
!! - \ref fem_quad_cache::oft_qcache_geom "oft_qcache_geom": per-mesh/per-quadrature geometry
!!   (logical gradient vectors `gop`, their cross products `cgop`, Jacobian determinants,
!!   per-cell entity orientation codes, and optionally physical quadrature points and
!!   thread-partition boundary flags).
!! - \ref fem_quad_cache::oft_fem_qcache "oft_fem_qcache": basis data for one FE space
!!   (Lagrange, \f$ H^1 \f$ or H(Curl)) on that geometry, in one of two modes:
!!   - **FULL** (\ref fem_quad_cache::qcache_mode_full "qcache_mode_full"): physical basis
!!     values/gradients/curls stored for every (cell, quadrature point). Simple lookup, but
!!     memory scales as `nce*3*nqp*nc`.
!!   - **REFERENCE** (\ref fem_quad_cache::qcache_mode_ref "qcache_mode_ref"): cell-independent
!!     reference tables of the logical components of every basis function, one block per
!!     (local entity, orientation state), plus the per-cell geometry above. Physical quantities
!!     are rebuilt on the fly with `gop`/`cgop`.
!!
!! Layout and conventions:
!! - All tables are plain contiguous arrays with the DOF index fastest:
!!   `full(dof,comp,qp,cell)` and `ref(row,lcomp,qp)`. A sum over DOFs (field reconstruction)
!!   and a loop over test functions (residual accumulation) are therefore both unit-stride, and
!!   all data for one (cell, qp) pair is one contiguous block of `nce*ncomp` values (also usable
!!   as a GEMM operand over quadrature points).
!! - Logical components follow the existing basis evaluators: physical vector values and
!!   gradients are `sum_k L_k gop(:,k)` (`k=1..4` for tets, `1..3` for hexes) and curls are
!!   `sum_k C_k cgop(:,k)` (6 cross products for tets, 3 for hexes).
!! - Every DOF belongs to one entity (vertex, edge, face or cell interior), and its function
!!   depends only on that entity's orientation: edges have two states (`mesh%%lce` sign) and faces
!!   have `2*face_np` states (`mesh%%lcfo` code). The reference tables are generated by calling
!!   the standard evaluators on a small internal "orientation template" mesh whose cells enumerate
!!   all states, so they match the evaluators exactly. The per-entity assumption is checked
!!   against direct evaluation on real meshes by `tests/fem/test_fem_qcache`.
!!
!! Kernel routines (\ref fem_quad_cache::fem_qcache_cell_rows "fem_qcache_cell_rows",
!! \ref fem_quad_cache::fem_qcache_eval "fem_qcache_eval",
!! \ref fem_quad_cache::fem_qcache_interp "fem_qcache_interp",
!! \ref fem_quad_cache::fem_qcache_accum "fem_qcache_accum",
!! \ref fem_quad_cache::fem_qcache_geom_get "fem_qcache_geom_get") contain no allocation,
!! type-bound calls or `SELECT TYPE`, use no module or threadprivate state, and are safe to call
!! concurrently from OpenMP threads once setup is complete.
!!
!! @authors Chris Hansen
!! @date November 2026
!! @ingroup doxy_oft_fem
!------------------------------------------------------------------------------
