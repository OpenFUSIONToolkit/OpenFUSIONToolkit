!---Transform types (physical = logical . transform)
INTEGER(i4), PARAMETER :: qc_xform_none = 0 !< Scalar, no transform
INTEGER(i4), PARAMETER :: qc_xform_gop = 1 !< Transform with `gop`
INTEGER(i4), PARAMETER :: qc_xform_cgop = 2 !< Transform with `cgop`
!------------------------------------------------------------------------------
!> Per-cell geometry and orientation data at quadrature points for one mesh and quadrature rule
!!
!! Geometry entry `g` for (cell, qp) is `goff(cell) + (qp-1)*gstride(cell)`, where `gstride` is
!! 0 for cells with a constant Jacobian (straight tets, affine hexes) and 1 otherwise.
!------------------------------------------------------------------------------
TYPE, PUBLIC :: oft_qcache_geom
  INTEGER(i4) :: nc = 0 !< Number of cells
  INTEGER(i4) :: nqp = 0 !< Number of quadrature points
  INTEGER(i4) :: nlog = 0 !< Number of logical gradient vectors (4 tet, 3 hex)
  INTEGER(i4) :: ncurl = 0 !< Number of stored `gop` cross products (6 tet, 3 hex)
  INTEGER(i4) :: ne = 0 !< Edges per cell
  INTEGER(i4) :: nf = 0 !< Faces per cell
  INTEGER(i4) :: nfs = 0 !< Orientation states per face (`2*face_np`)
  INTEGER(i4) :: ngeom = 0 !< Number of stored geometry entries
  INTEGER(i4) :: nvar = 0 !< Number of cells with per-qp geometry
  INTEGER(i4) :: hc(6) = 0 !< Columns of the full `cgop(3,6)` that are stored
  REAL(r8) :: setup_time = 0.d0 !< Wall time for setup [s]
  CLASS(oft_mesh), POINTER :: mesh => NULL() !< Mesh
  REAL(r8), CONTIGUOUS, POINTER, DIMENSION(:,:) :: pts => NULL() !< Quadrature points (copy) [:,nqp]
  REAL(r8), CONTIGUOUS, POINTER, DIMENSION(:) :: wts => NULL() !< Quadrature weights (copy) [nqp]
  INTEGER(i4), CONTIGUOUS, POINTER, DIMENSION(:) :: goff => NULL() !< First geometry entry of each cell [nc]
  INTEGER(i4), CONTIGUOUS, POINTER, DIMENSION(:) :: gstride => NULL() !< Geometry stride per qp (0 or 1) [nc]
  REAL(r8), CONTIGUOUS, POINTER, DIMENSION(:,:,:) :: gop => NULL() !< Logical gradient vectors [3,nlog,ngeom]
  REAL(r8), CONTIGUOUS, POINTER, DIMENSION(:,:,:) :: cgop => NULL() !< Cross products of `gop` [3,ncurl,ngeom]
  REAL(r8), CONTIGUOUS, POINTER, DIMENSION(:) :: det => NULL() !< Jacobian determinant [ngeom]
  INTEGER(i4), CONTIGUOUS, POINTER, DIMENSION(:,:) :: orient => NULL() !< Edge (1:ne) and face (ne+1:ne+nf) orientation states [ne+nf,nc]
  REAL(r8), CONTIGUOUS, POINTER, DIMENSION(:,:,:) :: pt => NULL() !< Physical quadrature points (optional) [3,nqp,nc]
  LOGICAL, CONTIGUOUS, POINTER, DIMENSION(:) :: cell_shared => NULL() !< Cell touches DOFs of another thread partition (optional) [nc]
CONTAINS
  !> Build geometry cache
  PROCEDURE :: setup => qcache_geom_setup
  !> Free geometry cache
  PROCEDURE :: delete => qcache_geom_delete
  !> Memory used [bytes]
  PROCEDURE :: mem => qcache_geom_mem
END TYPE oft_qcache_geom
!------------------------------------------------------------------------------
!> One cached basis quantity (values, gradients or curls)
!------------------------------------------------------------------------------
TYPE, PUBLIC :: oft_qcache_quant
  INTEGER(i4) :: xform = -1 !< Transform type (-1 if not stored)
  INTEGER(i4) :: nlc = 0 !< Number of logical components
  INTEGER(i4) :: npc = 0 !< Number of physical components (1 or 3)
  REAL(r8), CONTIGUOUS, POINTER, DIMENSION(:,:,:) :: ref => NULL() !< Reference table (REFERENCE mode) [nrows,nlc,nqp]
  REAL(r8), CONTIGUOUS, POINTER, DIMENSION(:,:,:,:) :: full => NULL() !< Physical table (FULL mode) [nce,npc,nqp,nc]
END TYPE oft_qcache_quant
!------------------------------------------------------------------------------
!> Quadrature-point basis cache for one 3D FE space
!!
!! In REFERENCE mode, row `ent_row0(s,e)+j` of `q(:)%ref` holds DOF `j` of local entity `e`
!! in orientation state `s`. Entities are numbered vertices, edges, faces, then the cell
!! interior, matching the local DOF ordering of \ref fem_base::oft_fem_type "oft_fem_type".
!------------------------------------------------------------------------------
TYPE, PUBLIC :: oft_fem_qcache
  INTEGER(i4) :: mode = qcache_mode_none !< Cache mode
  INTEGER(i4) :: basis = 0 !< Basis kind (`qcache_basis_*`)
  INTEGER(i4) :: nce = 0 !< DOFs per cell
  INTEGER(i4) :: nqp = 0 !< Number of quadrature points
  INTEGER(i4) :: nc = 0 !< Number of cells
  INTEGER(i4) :: nent = 0 !< Entities per cell
  INTEGER(i4) :: nstmax = 0 !< Maximum orientation states per entity
  INTEGER(i4) :: nrows = 0 !< Number of reference table rows
  REAL(r8) :: setup_time = 0.d0 !< Wall time for setup [s]
  INTEGER(i4), CONTIGUOUS, POINTER, DIMENSION(:) :: ent_ndof => NULL() !< DOFs per entity [nent]
  INTEGER(i4), CONTIGUOUS, POINTER, DIMENSION(:) :: ent_dof0 => NULL() !< Local DOF offset per entity [nent]
  INTEGER(i4), CONTIGUOUS, POINTER, DIMENSION(:) :: ent_orient => NULL() !< Row of `geom%%orient` (0 = single state) [nent]
  INTEGER(i4), CONTIGUOUS, POINTER, DIMENSION(:) :: ent_nst => NULL() !< Orientation states per entity [nent]
  INTEGER(i4), CONTIGUOUS, POINTER, DIMENSION(:,:) :: ent_row0 => NULL() !< Row offset per (state, entity) [nstmax,nent]
  TYPE(oft_qcache_quant) :: q(3) !< Cached quantities (`qcache_val`, `qcache_grad`, `qcache_curl`)
  CLASS(oft_fem_type), POINTER :: fe => NULL() !< FE space
  TYPE(oft_qcache_geom), POINTER :: geom => NULL() !< Geometry cache
CONTAINS
  !> Build basis cache
  PROCEDURE :: setup => fem_qcache_setup
  !> Free basis cache
  PROCEDURE :: delete => fem_qcache_delete
  !> Memory used [bytes]
  PROCEDURE :: mem => fem_qcache_mem
  !> Is the cache set up?
  PROCEDURE :: ready => fem_qcache_ready
END TYPE oft_fem_qcache
