!---Cache modes
INTEGER(i4), PARAMETER, PUBLIC :: qcache_mode_none = 0 !< Cache not set up
INTEGER(i4), PARAMETER, PUBLIC :: qcache_mode_full = 1 !< Physical basis data at every (cell, qp)
INTEGER(i4), PARAMETER, PUBLIC :: qcache_mode_ref = 2 !< Reference tables + per-cell geometry
!---Quantity indices
INTEGER(i4), PARAMETER, PUBLIC :: qcache_val = 1 !< Basis values (scalar, or vector for H(Curl))
INTEGER(i4), PARAMETER, PUBLIC :: qcache_grad = 2 !< Basis gradients
INTEGER(i4), PARAMETER, PUBLIC :: qcache_curl = 3 !< Basis curls
!---Basis kinds
