END FUNCTION fem_qcache_ready
!------------------------------------------------------------------------------
!> Can the canonical-frame path (kernels without `rows`) be used?
!!
!! True if the cache is set up and every oriented entity's functions are a linear
!! combination of canonical functions of the same space (see \ref qcache_build_xform). This
!! holds for Lagrange and \f$ H^1 \f$ on tets and hexes and for H(Curl) on hexes, but not for
!! H(Curl) faces on tets (order > 1), which differ by gradients that are not in OFT's
!! (gradient-free) H(Curl) space. Use the gather path (`rows`) when false.
!------------------------------------------------------------------------------
FUNCTION fem_qcache_canonical_ok(self) RESULT(ok)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
LOGICAL :: ok
ok=fem_qcache_ready(self).AND.(self%nxf(3)==0)
END FUNCTION fem_qcache_canonical_ok
!------------------------------------------------------------------------------
!> Get reference table rows of all local DOFs of a cell
!!
!! Call once per cell; the result is passed to the per-qp kernels.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_cell_rows(self,cell,rows)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(out) :: rows(:) !< Table row of each local DOF [nce]
INTEGER(i4) :: i,j,s,row0,d0
DO i=1,self%nent
  s=1
  IF(self%ent_orient(i)>0)s=self%geom%orient(self%ent_orient(i),cell)
  row0=self%ent_row0(s,i)
  d0=self%ent_dof0(i)
  DO j=1,self%ent_ndof(i)
    rows(d0+j)=row0+j
  END DO
END DO
END SUBROUTINE fem_qcache_cell_rows
!------------------------------------------------------------------------------
!> Fit the orientation transforms of every (entity, state) from the reference tables
!!
!! For each entity with `nd` DOFs and state `s>1`, solves the least-squares problem
!! \f$ \phi^s_j(x_m) = \sum_r M_{jr} \phi^1_{r}(x_m) \f$ over all quadrature points and all
!! cached quantities and logical components (LAPACK `dgels`), first with the entity's own
!! canonical functions as regressors `r`. If that does not reproduce the oriented functions, the
!! canonical functions of the entity's vertices, edges and (for faces) the cell interior are
!! added, and finally all canonical functions of the cell. Transforms within 1E-10 of a signed
!! permutation of the own block are stored exactly as such (kind 0 if the identity, kind 1 otherwise), others
!! as dense `nd x nreg` blocks with a regressor list (kind 2). If no fit reaches `qcache_xf_tol`
!! the pair is marked kind 3: the oriented functions are not in the span of this space's
!! canonical functions, and the state's own table block must be used (gather path, or the
!! per-entity correction in the cell kernels). The maximum relative residual of the accepted
!! fits is stored in `xf_resid`.
!------------------------------------------------------------------------------
SUBROUTINE qcache_build_xform(self)
CLASS(oft_fem_qcache), INTENT(inout) :: self !< Basis cache
INTEGER(i4) :: i,s,nd,iq,nm,j,ii,np_tot,nv_tot,nr_tot,cnt,nreg,nsub,nv,ne,e,v
INTEGER(i4), ALLOCATABLE, DIMENSION(:) :: perm,regs,sub_ent
REAL(r8) :: resid
REAL(r8), ALLOCATABLE, DIMENSION(:) :: sgn
REAL(r8), ALLOCATABLE, DIMENSION(:,:) :: x
LOGICAL :: is_perm
CLASS(oft_mesh), POINTER :: mesh
mesh=>self%fe%mesh
nv=mesh%cell_np
ne=mesh%cell_ne
ALLOCATE(self%xf_kind(self%nstmax,self%nent),self%xf_off(self%nstmax,self%nent))
ALLOCATE(self%xf_nreg(self%nstmax,self%nent),self%xf_roff(self%nstmax,self%nent))
self%xf_kind=0
self%xf_off=0
self%xf_nreg=0
self%xf_roff=0
self%nxf=0
self%xf_resid=0.d0
!---Number of samples per DOF
nm=0
DO iq=1,3
  IF(self%q(iq)%xform<0)CYCLE
  nm=nm+self%q(iq)%nlc*self%nqp
END DO
!---Storage upper bounds (all DOFs of the cell as regressors)
np_tot=0; nv_tot=0; nr_tot=0
DO i=1,self%nent
  nd=self%ent_ndof(i)
  DO s=2,self%ent_nst(i)
    np_tot=np_tot+nd
    nv_tot=nv_tot+nd*self%nce
    nr_tot=nr_tot+self%nce
  END DO
END DO
ALLOCATE(self%xf_perm(MAX(1,np_tot)),self%xf_sgn(MAX(1,np_tot)),self%xf_mat(MAX(1,nv_tot)))
ALLOCATE(self%xf_reg(MAX(1,nr_tot)))
self%xf_perm=0
self%xf_sgn=0.d0
self%xf_mat=0.d0
self%xf_reg=0
np_tot=0; nv_tot=0; nr_tot=0
ALLOCATE(regs(self%nce),sub_ent(self%nent))
DO i=1,self%nent
  nd=self%ent_ndof(i)
  IF(nd==0)CYCLE
  !---Sub-entities (vertices of edges; vertices and edges of faces)
  nsub=0
  IF(i>nv.AND.i<=nv+ne)THEN
    e=i-nv
    sub_ent(1:2)=mesh%cell_ed(:,e)
    nsub=2
  ELSE IF(i>nv+ne.AND.i<self%nent)THEN
    j=i-nv-ne
    DO v=1,mesh%face_np
      nsub=nsub+1
      sub_ent(nsub)=mesh%cell_fc(v,j)
    END DO
    DO e=1,ne
      IF(ANY(mesh%cell_fc(:,j)==mesh%cell_ed(1,e)).AND.ANY(mesh%cell_fc(:,j)==mesh%cell_ed(2,e)))THEN
        nsub=nsub+1
        sub_ent(nsub)=nv+e
      END IF
    END DO
    ! Interior bubbles vanish on all faces, so they can absorb orientation-dependent extensions
    nsub=nsub+1
    sub_ent(nsub)=self%nent
  END IF
  DO s=2,self%ent_nst(i)
    !---Own block only
    nreg=nd
    DO j=1,nd
      regs(j)=self%ent_dof0(i)+j
    END DO
    ALLOCATE(x(self%nce,nd))
    CALL fit(nreg,x,resid)
    IF(resid>qcache_xf_tol.AND.nsub>0)THEN
      !---Add canonical functions of sub-entities
      DO ii=1,nsub
        DO j=1,self%ent_ndof(sub_ent(ii))
          nreg=nreg+1
          regs(nreg)=self%ent_dof0(sub_ent(ii))+j
        END DO
      END DO
      CALL fit(nreg,x,resid)
    END IF
    IF(resid>qcache_xf_tol)THEN
      !---Last resort: all canonical functions of the cell
      nreg=self%nce
      DO j=1,self%nce
        regs(j)=j
      END DO
      CALL fit(nreg,x,resid)
    END IF
    IF(resid>qcache_xf_tol)THEN
      !---No transform within this space: use the state's own table block (kind 3)
      self%xf_kind(s,i)=3
      self%nxf(3)=self%nxf(3)+1
      DEALLOCATE(x)
      CYCLE
    END IF
    self%xf_resid=MAX(self%xf_resid,resid)
    !---Signed permutation of own block?
    ALLOCATE(perm(nd),sgn(nd))
    is_perm=.TRUE.
    perm=0
    sgn=0.d0
    DO j=1,nd
      cnt=0
      DO ii=1,nreg
        IF(ABS(x(ii,j))>1.d-10)THEN
          IF(ABS(ABS(x(ii,j))-1.d0)>1.d-10.OR.ii>nd)is_perm=.FALSE.
          cnt=cnt+1
          perm(j)=ii
          sgn(j)=SIGN(1.d0,x(ii,j))
        END IF
      END DO
      IF(cnt/=1)is_perm=.FALSE.
    END DO
    IF(is_perm)THEN
      DO ii=1,nd
        IF(COUNT(perm==ii)/=1)is_perm=.FALSE.
      END DO
    END IF
    !---Store
    IF(is_perm)THEN
      self%xf_kind(s,i)=1
      IF(ALL(sgn>0.d0))THEN
        IF(ALL(perm==(/(j,j=1,nd)/)))self%xf_kind(s,i)=0
      END IF
      self%xf_off(s,i)=np_tot
      self%xf_perm(np_tot+1:np_tot+nd)=perm
      self%xf_sgn(np_tot+1:np_tot+nd)=sgn
      np_tot=np_tot+nd
    ELSE
      self%xf_kind(s,i)=2
      self%xf_off(s,i)=nv_tot
      self%xf_nreg(s,i)=nreg
      self%xf_roff(s,i)=nr_tot
      self%xf_reg(nr_tot+1:nr_tot+nreg)=regs(1:nreg)
      nr_tot=nr_tot+nreg
      ! M(j,r) stored column-major (j fastest)
      DO ii=1,nreg
        DO j=1,nd
          self%xf_mat(nv_tot+(ii-1)*nd+j)=x(ii,j)
        END DO
      END DO
      nv_tot=nv_tot+nd*nreg
    END IF
    self%nxf(self%xf_kind(s,i))=self%nxf(self%xf_kind(s,i))+1
    DEALLOCATE(x,perm,sgn)
  END DO
END DO
DEALLOCATE(regs,sub_ent)
IF(oft_debug_print(1))WRITE(*,'(2A,4I6,A,ES10.2)')oft_indent, &
  'qcache orientation transforms (identity/signed perm/dense/none): ',self%nxf,', fit residual = ',self%xf_resid
CONTAINS
!> Least-squares fit of the state-s block of entity i against canonical rows regs(1:nr)
SUBROUTINE fit(nr,xfit,res)
INTEGER(i4), INTENT(in) :: nr
REAL(r8), INTENT(out) :: xfit(:,:)
REAL(r8), INTENT(out) :: res
INTEGER(i4) :: k,m,mm,jj,rr,info,lwork
REAL(r8), ALLOCATABLE, DIMENSION(:) :: work
REAL(r8), ALLOCATABLE, DIMENSION(:,:) :: amat,bmat,a0,b0
EXTERNAL :: dgels
ALLOCATE(amat(nm,nr),bmat(nm,nd),a0(nm,nr),b0(nm,nd))
mm=0
DO iq=1,3
  IF(self%q(iq)%xform<0)CYCLE
  DO m=1,self%nqp
    DO k=1,self%q(iq)%nlc
      mm=mm+1
      DO rr=1,nr
        amat(mm,rr)=self%q(iq)%ref(regs(rr),k,m)
      END DO
      DO jj=1,nd
        bmat(mm,jj)=self%q(iq)%ref(self%ent_row0(s,i)+jj,k,m)
      END DO
    END DO
  END DO
END DO
a0=amat; b0=bmat
ALLOCATE(work(1))
CALL dgels('N',nm,nr,nd,amat,nm,bmat,nm,work,-1,info)
lwork=INT(work(1),4)
DEALLOCATE(work)
ALLOCATE(work(lwork))
CALL dgels('N',nm,nr,nd,amat,nm,bmat,nm,work,lwork,info)
DEALLOCATE(work)
IF(info/=0)CALL oft_abort('Orientation transform fit failed','qcache_build_xform',__FILE__)
xfit(1:nr,:)=bmat(1:nr,1:nd)
! Snap round-off to zero/+-1 for exact permutations and sparsity
DO jj=1,nd
  DO rr=1,nr
    IF(ABS(xfit(rr,jj))<1.d-13)xfit(rr,jj)=0.d0
    IF(ABS(ABS(xfit(rr,jj))-1.d0)<1.d-13)xfit(rr,jj)=SIGN(1.d0,xfit(rr,jj))
  END DO
END DO
res=MAXVAL(ABS(b0-MATMUL(a0,xfit(1:nr,:))))/MAXVAL(ABS(a0))
DEALLOCATE(amat,bmat,a0,b0)
END SUBROUTINE fit
END SUBROUTINE qcache_build_xform
!------------------------------------------------------------------------------
!> Apply the orientation transforms of a cell to vectors, `v = M v_ref` (cell frame from
!! canonical frame), or `v_ref = M^T v` (`transpose`)
!------------------------------------------------------------------------------
SUBROUTINE qcache_apply_xform(self,cell,v,ldv,nvec,transpose)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: ldv !< Leading dimension of `v`
INTEGER(i4), INTENT(in) :: nvec !< Number of vectors
REAL(r8), INTENT(inout) :: v(ldv,*) !< Vectors [nce,nvec]
LOGICAL, INTENT(in) :: transpose !< Apply \f$ M^T \f$ instead of \f$ M \f$
INTEGER(i4) :: i,s,nd,d0,o,ro,j,r,f,kind
REAL(r8) :: tmp(self%nce),acc
IF(self%nxf(3)>0)CALL oft_abort('Orientation transforms not available', &
  'qcache_apply_xform',__FILE__)
DO f=1,nvec
  tmp=v(1:self%nce,f)
  IF(transpose)v(1:self%nce,f)=0.d0
  DO i=1,self%nent
    nd=self%ent_ndof(i)
    d0=self%ent_dof0(i)
    kind=0
    IF(self%ent_orient(i)>0)THEN
      s=self%geom%orient(self%ent_orient(i),cell)
      kind=self%xf_kind(s,i)
      o=self%xf_off(s,i)
    END IF
    SELECT CASE(kind)
    CASE(0)
      IF(transpose)THEN
        DO j=1,nd
          v(d0+j,f)=v(d0+j,f)+tmp(d0+j)
        END DO
      END IF
    CASE(1)
      IF(transpose)THEN
        DO j=1,nd
          v(d0+self%xf_perm(o+j),f)=v(d0+self%xf_perm(o+j),f)+self%xf_sgn(o+j)*tmp(d0+j)
        END DO
      ELSE
        DO j=1,nd
          v(d0+j,f)=self%xf_sgn(o+j)*tmp(d0+self%xf_perm(o+j))
        END DO
      END IF
    CASE(2)
      ro=self%xf_roff(s,i)
      IF(transpose)THEN
        DO r=1,self%xf_nreg(s,i)
          acc=0.d0
          DO j=1,nd
            acc=acc+self%xf_mat(o+(r-1)*nd+j)*tmp(d0+j)
          END DO
          v(self%xf_reg(ro+r),f)=v(self%xf_reg(ro+r),f)+acc
        END DO
      ELSE
        DO j=1,nd
          v(d0+j,f)=0.d0
        END DO
        DO r=1,self%xf_nreg(s,i)
          acc=tmp(self%xf_reg(ro+r))
          DO j=1,nd
            v(d0+j,f)=v(d0+j,f)+self%xf_mat(o+(r-1)*nd+j)*acc
          END DO
        END DO
      END IF
    END SELECT
  END DO
END DO
END SUBROUTINE qcache_apply_xform
!------------------------------------------------------------------------------
!> Transform local DOF coefficients of a cell to the canonical (state 1) frame, in place
!!
!! After this call, fields can be reconstructed with the kernels without `rows`.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_coefs_to_ref(self,cell,coefs,nfld)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: nfld !< Number of fields
REAL(r8), CONTIGUOUS, INTENT(inout) :: coefs(:,:) !< Local coefficients [nce,nfld]
CALL qcache_apply_xform(self,cell,coefs,SIZE(coefs,1),nfld,.TRUE.)
END SUBROUTINE fem_qcache_coefs_to_ref
!------------------------------------------------------------------------------
!> Transform local results accumulated in the canonical frame to the cell's DOFs, in place
!!
!! Use after accumulating with the kernels without `rows`.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_res_from_ref(self,cell,res,nfld)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: nfld !< Number of vectors
REAL(r8), CONTIGUOUS, INTENT(inout) :: res(:,:) !< Local results [nce,nfld]
CALL qcache_apply_xform(self,cell,res,SIZE(res,1),nfld,.FALSE.)
END SUBROUTINE fem_qcache_res_from_ref
!------------------------------------------------------------------------------
!> Transform a local matrix assembled in the canonical frames of a row and a column space
!! to the cell's DOFs, in place (\f$ K = T_r K_{ref} T_c^T \f$)
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_mat_from_ref(rcache,ccache,cell,mat)
TYPE(oft_fem_qcache), INTENT(in) :: rcache !< Row space cache
TYPE(oft_fem_qcache), INTENT(in) :: ccache !< Column space cache
INTEGER(i4), INTENT(in) :: cell !< Cell index
REAL(r8), CONTIGUOUS, INTENT(inout) :: mat(:,:) !< Local matrix [rcache%nce,ccache%nce]
INTEGER(i4) :: i
REAL(r8) :: row(SIZE(mat,2),1)
CALL qcache_apply_xform(rcache,cell,mat,SIZE(mat,1),SIZE(mat,2),.FALSE.)
DO i=1,SIZE(mat,1)
  row(:,1)=mat(i,:)
  CALL qcache_apply_xform(ccache,cell,row,SIZE(mat,2),1,.FALSE.)
  mat(i,:)=row(:,1)
END DO
END SUBROUTINE fem_qcache_mat_from_ref
!------------------------------------------------------------------------------
!> Get the transform matrix (`gop` or `cgop` columns) of quantity `iq` at (cell, qp)
!------------------------------------------------------------------------------
SUBROUTINE qcache_get_x(self,iq,cell,qp,x)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: iq !< Quantity
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: qp !< Quadrature point index
REAL(r8), INTENT(out) :: x(3,6) !< Transform columns
INTEGER(i4) :: g
g=self%geom%goff(cell)+(qp-1)*self%geom%gstride(cell)
IF(self%q(iq)%xform==qc_xform_gop)THEN
  x(:,1:self%q(iq)%nlc)=self%geom%gop(:,:,g)
ELSE IF(self%q(iq)%xform==qc_xform_cgop)THEN
  x(:,1:self%q(iq)%nlc)=self%geom%cgop(:,:,g)
END IF
END SUBROUTINE qcache_get_x
!------------------------------------------------------------------------------
!> Evaluate a physical basis quantity for all DOFs at (cell, qp)
!!
!! - With `rows`, the cell's basis is rebuilt exactly from the gathered table rows.
!! - Without `rows`, the canonical-frame basis \f$ \phi^1 \f$ is rebuilt (contiguous access); local
!!   matrices built from it are mapped with \ref fem_qcache_mat_from_ref.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_eval(self,iq,cell,qp,out,rows)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: iq !< Quantity (`qcache_val`, `qcache_grad`, `qcache_curl`)
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: qp !< Quadrature point index
REAL(r8), CONTIGUOUS, INTENT(out) :: out(:,:) !< Physical quantity [nce,npc]
INTEGER(i4), OPTIONAL, INTENT(in) :: rows(:) !< Table rows from \ref fem_qcache_cell_rows [nce]
INTEGER(i4) :: j,k,c,nce,nlc
REAL(r8) :: x(3,6),l
nce=self%nce
nlc=self%q(iq)%nlc
IF(self%q(iq)%xform==qc_xform_none)THEN
  IF(PRESENT(rows))THEN
    DO j=1,nce
      out(j,1)=self%q(iq)%ref(rows(j),1,qp)
    END DO
  ELSE
    out(1:nce,1)=self%q(iq)%ref(1:nce,1,qp)
  END IF
  RETURN
END IF
CALL qcache_get_x(self,iq,cell,qp,x)
IF(PRESENT(rows))THEN
  DO j=1,nce
    l=self%q(iq)%ref(rows(j),1,qp)
    out(j,1)=l*x(1,1)
    out(j,2)=l*x(2,1)
    out(j,3)=l*x(3,1)
  END DO
  DO k=2,nlc
    DO j=1,nce
      l=self%q(iq)%ref(rows(j),k,qp)
      out(j,1)=out(j,1)+l*x(1,k)
      out(j,2)=out(j,2)+l*x(2,k)
      out(j,3)=out(j,3)+l*x(3,k)
    END DO
  END DO
ELSE
  DO c=1,3
    DO j=1,nce
      out(j,c)=self%q(iq)%ref(j,1,qp)*x(c,1)
    END DO
    DO k=2,nlc
      DO j=1,nce
        out(j,c)=out(j,c)+self%q(iq)%ref(j,k,qp)*x(c,k)
      END DO
    END DO
  END DO
END IF
END SUBROUTINE fem_qcache_eval
!------------------------------------------------------------------------------
!> Evaluate a physical basis quantity for all DOFs and quadrature points of a cell
!!
!! Produces a `(nce,npc,nqp)` block, eg. as a GEMM operand for local matrix assembly. Without
!! `rows`, the canonical-frame basis is returned (see \ref fem_qcache_eval).
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_eval_cell(self,iq,cell,out,rows)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: iq !< Quantity (`qcache_val`, `qcache_grad`, `qcache_curl`)
INTEGER(i4), INTENT(in) :: cell !< Cell index
REAL(r8), CONTIGUOUS, INTENT(out) :: out(:,:,:) !< Physical quantity [nce,npc,nqp]
INTEGER(i4), OPTIONAL, INTENT(in) :: rows(:) !< Table rows from \ref fem_qcache_cell_rows [nce]
INTEGER(i4) :: m
DO m=1,self%nqp
  CALL fem_qcache_eval(self,iq,cell,m,out(:,:,m),rows)
END DO
END SUBROUTINE fem_qcache_eval_cell
!------------------------------------------------------------------------------
!> Reconstruct fields from local DOF coefficients at (cell, qp)
!!
!! Computes `out(c,f) = sum_j coefs(j,f)*phi_j,c` for `nfld` fields at once. The coefficients are
!! contracted with the logical table first and the geometry transform is applied once per field,
!! so the physical basis is never formed. Without `rows`, canonical-frame coefficients are
!! expected (\ref fem_qcache_coefs_to_ref).
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_interp(self,iq,cell,qp,coefs,nfld,out,rows)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: iq !< Quantity (`qcache_val`, `qcache_grad`, `qcache_curl`)
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: qp !< Quadrature point index
REAL(r8), CONTIGUOUS, INTENT(in) :: coefs(:,:) !< Local DOF coefficients [nce,nfld]
INTEGER(i4), INTENT(in) :: nfld !< Number of fields
REAL(r8), INTENT(out) :: out(:,:) !< Reconstructed fields [npc,nfld]
INTEGER(i4), OPTIONAL, INTENT(in) :: rows(:) !< Table rows from \ref fem_qcache_cell_rows [nce]
INTEGER(i4) :: j,k,c,f,nlc,nce,r
REAL(r8) :: x(3,6),lc(6),tmp,t1,t2,t3,cj
nce=self%nce
nlc=self%q(iq)%nlc
DO f=1,nfld
  !---Logical components (nlc is 1 or 3)
  IF(nlc==1)THEN
    tmp=0.d0
    IF(PRESENT(rows))THEN
      DO j=1,nce
        tmp=tmp+coefs(j,f)*self%q(iq)%ref(rows(j),1,qp)
      END DO
    ELSE
      !$omp simd reduction(+:tmp)
      DO j=1,nce
        tmp=tmp+coefs(j,f)*self%q(iq)%ref(j,1,qp)
      END DO
    END IF
    lc(1)=tmp
  ELSE
    t1=0.d0; t2=0.d0; t3=0.d0
    IF(PRESENT(rows))THEN
      DO j=1,nce
        cj=coefs(j,f); r=rows(j)
        t1=t1+cj*self%q(iq)%ref(r,1,qp)
        t2=t2+cj*self%q(iq)%ref(r,2,qp)
        t3=t3+cj*self%q(iq)%ref(r,3,qp)
      END DO
    ELSE
      !$omp simd reduction(+:t1,t2,t3) private(cj)
      DO j=1,nce
        cj=coefs(j,f)
        t1=t1+cj*self%q(iq)%ref(j,1,qp)
        t2=t2+cj*self%q(iq)%ref(j,2,qp)
        t3=t3+cj*self%q(iq)%ref(j,3,qp)
      END DO
    END IF
    lc(1)=t1; lc(2)=t2; lc(3)=t3
  END IF
  !---Physical components
  IF(self%q(iq)%xform==qc_xform_none)THEN
    out(1,f)=lc(1)
  ELSE
    IF(f==1)CALL qcache_get_x(self,iq,cell,qp,x)
    DO c=1,3
      tmp=0.d0
      DO k=1,nlc
        tmp=tmp+x(c,k)*lc(k)
      END DO
      out(c,f)=tmp
    END DO
  END IF
END DO
END SUBROUTINE fem_qcache_interp
!------------------------------------------------------------------------------
!> Accumulate a test-function contraction at (cell, qp)
!!
!! Computes `res(j) = res(j) + sum_c phi_j,c * flux(c)` for all local DOFs. The flux is
!! transformed to logical components once, so the physical basis is never formed. Without
!! `rows`, the result is accumulated in the canonical frame (map the final result with
!! \ref fem_qcache_res_from_ref). Quadrature weights and Jacobian determinants must be included in
!! `flux` by the caller.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_accum(self,iq,cell,qp,flux,res,rows)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: iq !< Quantity (`qcache_val`, `qcache_grad`, `qcache_curl`)
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: qp !< Quadrature point index
REAL(r8), INTENT(in) :: flux(:) !< Physical flux [npc]
REAL(r8), CONTIGUOUS, INTENT(inout) :: res(:) !< Local residual [nce]
INTEGER(i4), OPTIONAL, INTENT(in) :: rows(:) !< Table rows from \ref fem_qcache_cell_rows [nce]
INTEGER(i4) :: j,k,nlc,nce
REAL(r8) :: x(3,6),lf(6),tmp
nce=self%nce
nlc=self%q(iq)%nlc
IF(self%q(iq)%xform==qc_xform_none)THEN
  lf(1)=flux(1)
ELSE
  CALL qcache_get_x(self,iq,cell,qp,x)
  DO k=1,nlc
    lf(k)=x(1,k)*flux(1)+x(2,k)*flux(2)+x(3,k)*flux(3)
  END DO
END IF
IF(PRESENT(rows))THEN
  DO k=1,nlc
    tmp=lf(k)
    DO j=1,nce
      res(j)=res(j)+self%q(iq)%ref(rows(j),k,qp)*tmp
    END DO
  END DO
ELSE
  DO k=1,nlc
    tmp=lf(k)
    DO j=1,nce
      res(j)=res(j)+self%q(iq)%ref(j,k,qp)*tmp
    END DO
  END DO
END IF
END SUBROUTINE fem_qcache_accum
!------------------------------------------------------------------------------
!> Workspace size (doubles) needed by \ref fem_qcache_interp_cell and \ref fem_qcache_accum_cell
!------------------------------------------------------------------------------
PURE FUNCTION fem_qcache_work_size(self,nfld) RESULT(n)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: nfld !< Number of fields
INTEGER(i4) :: n !< Workspace size
n=(self%nce+3*self%nqp)*nfld
END FUNCTION fem_qcache_work_size
!------------------------------------------------------------------------------
!> Reconstruct fields at all quadrature points of a cell (cell-batched kernel)
!!
!! Computes `out(c,m,f) = sum_j coefs(j,f)*phi_j,c(x_m)`. The coefficients are mapped to the
!! canonical frame once (\ref qcache_to_canon), contracted with the canonical table
!! for all quadrature points at once (a `nce x (3*nqp)` by `nce x nfld` GEMM-shaped product),
!! corrected for entities without a transform (kind 3) with their own table blocks, and finally
!! transformed with the per-qp geometry. No per-DOF gathers are needed.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_interp_cell(self,iq,cell,coefs,nfld,out,work)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: iq !< Quantity (`qcache_val`, `qcache_grad`, `qcache_curl`)
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: nfld !< Number of fields
REAL(r8), CONTIGUOUS, INTENT(in) :: coefs(:,:) !< Local DOF coefficients (cell frame) [nce,nfld]
REAL(r8), CONTIGUOUS, INTENT(out) :: out(:,:,:) !< Reconstructed fields [npc,nqp,nfld]
REAL(r8), CONTIGUOUS, INTENT(inout) :: work(:) !< Workspace [\ref fem_qcache_work_size]
INTEGER(i4) :: nce
nce=self%nce
CALL qcache_interp_cell_kernel(self,iq,cell,coefs,nfld,out,work(1:nce*nfld), &
  work(nce*nfld+1:nce*nfld+self%q(iq)%nlc*self%nqp*nfld),self%q(iq)%nlc)
END SUBROUTINE fem_qcache_interp_cell
!------------------------------------------------------------------------------
!> Implementation of \ref fem_qcache_interp_cell with the workspace split into its two parts
!------------------------------------------------------------------------------
SUBROUTINE qcache_interp_cell_kernel(self,iq,cell,coefs,nfld,out,cw,lc,nlc)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: iq !< Quantity
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: nfld !< Number of fields
REAL(r8), CONTIGUOUS, INTENT(in) :: coefs(:,:) !< Local DOF coefficients [nce,nfld]
REAL(r8), CONTIGUOUS, INTENT(out) :: out(:,:,:) !< Reconstructed fields [npc,nqp,nfld]
REAL(r8), INTENT(inout) :: cw(self%nce,nfld) !< Canonical-frame coefficients
INTEGER(i4), INTENT(in) :: nlc !< Logical components
REAL(r8), INTENT(inout) :: lc(nlc*self%nqp,nfld) !< Logical components at all qp
INTEGER(i4) :: i,j,f,kq,m,k,c,s,nd,d0,r0,nkq,nce,g
REAL(r8) :: tmp,x(3,3)
REAL(r8), CONTIGUOUS, POINTER :: tab(:,:)
nce=self%nce
nkq=nlc*self%nqp
tab(1:self%nrows,1:nkq)=>self%q(iq)%ref
!---Canonical-frame coefficients (kind 3 entities are excluded and corrected below)
CALL qcache_to_canon(self,cell,coefs,cw,nfld)
!---Contract with canonical table
DO f=1,nfld
  DO kq=1,nkq
    tmp=0.d0
    !$omp simd reduction(+:tmp)
    DO j=1,nce
      tmp=tmp+tab(j,kq)*cw(j,f)
    END DO
    lc(kq,f)=tmp
  END DO
END DO

!---Corrections for entities without a transform (unit-stride updates with the transposed table)
IF(self%nxf(3)>0)THEN
  DO i=1,self%nent
    IF(self%ent_orient(i)==0)CYCLE
    s=self%geom%orient(self%ent_orient(i),cell)
    IF(self%xf_kind(s,i)/=3)CYCLE
    nd=self%ent_ndof(i); d0=self%ent_dof0(i); r0=self%ent_row0(s,i)
    DO f=1,nfld
      DO j=1,nd
        tmp=coefs(d0+j,f)
        !$omp simd
        DO kq=1,nkq
          lc(kq,f)=lc(kq,f)+self%q(iq)%reft(kq,r0+j)*tmp
        END DO
      END DO
    END DO
  END DO
END IF
!---Geometry transform
IF(self%q(iq)%xform==qc_xform_none)THEN
  DO f=1,nfld
    DO m=1,self%nqp
      out(1,m,f)=lc(m,f)
    END DO
  END DO
  RETURN
END IF
DO m=1,self%nqp
  g=self%geom%goff(cell)+(m-1)*self%geom%gstride(cell)
  IF(self%q(iq)%xform==qc_xform_gop)THEN
    x=self%geom%gop(:,:,g)
  ELSE
    x=self%geom%cgop(:,:,g)
  END IF
  k=(m-1)*nlc
  DO f=1,nfld
    DO c=1,3
      out(c,m,f)=x(c,1)*lc(k+1,f)+x(c,2)*lc(k+2,f)+x(c,3)*lc(k+3,f)
    END DO
  END DO
END DO
END SUBROUTINE qcache_interp_cell_kernel
!------------------------------------------------------------------------------
!> Accumulate test-function contractions over all quadrature points of a cell (cell-batched)
!!
!! Computes `res(j,f) = res(j,f) + sum_m sum_c phi_j,c(x_m)*flux(c,m,f)`. Quadrature weights and
!! Jacobian determinants must be included in `flux`. The fluxes are transformed to logical
!! components per qp, contracted with the canonical table for all qp at once, and the result is
!! mapped back to the cell's DOFs (\ref qcache_from_canon), with kind 3 entities computed from
!! their own table blocks.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_accum_cell(self,iq,cell,flux,nfld,res,work)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: iq !< Quantity (`qcache_val`, `qcache_grad`, `qcache_curl`)
INTEGER(i4), INTENT(in) :: cell !< Cell index
REAL(r8), CONTIGUOUS, INTENT(in) :: flux(:,:,:) !< Physical fluxes [npc,nqp,nfld]
INTEGER(i4), INTENT(in) :: nfld !< Number of fields
REAL(r8), CONTIGUOUS, INTENT(inout) :: res(:,:) !< Local residuals (cell frame) [nce,nfld]
REAL(r8), CONTIGUOUS, INTENT(inout) :: work(:) !< Workspace [\ref fem_qcache_work_size]
INTEGER(i4) :: nce
nce=self%nce
CALL qcache_accum_cell_kernel(self,iq,cell,flux,nfld,res,work(1:nce*nfld), &
  work(nce*nfld+1:nce*nfld+self%q(iq)%nlc*self%nqp*nfld),self%q(iq)%nlc)
END SUBROUTINE fem_qcache_accum_cell
!------------------------------------------------------------------------------
!> Implementation of \ref fem_qcache_accum_cell with the workspace split into its two parts
!------------------------------------------------------------------------------
SUBROUTINE qcache_accum_cell_kernel(self,iq,cell,flux,nfld,res,rw,lf,nlc)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: iq !< Quantity
INTEGER(i4), INTENT(in) :: cell !< Cell index
REAL(r8), CONTIGUOUS, INTENT(in) :: flux(:,:,:) !< Physical fluxes [npc,nqp,nfld]
INTEGER(i4), INTENT(in) :: nfld !< Number of fields
REAL(r8), CONTIGUOUS, INTENT(inout) :: res(:,:) !< Local residuals [nce,nfld]
REAL(r8), INTENT(inout) :: rw(self%nce,nfld) !< Canonical-frame residuals
INTEGER(i4), INTENT(in) :: nlc !< Logical components
REAL(r8), INTENT(inout) :: lf(nlc*self%nqp,nfld) !< Logical fluxes at all qp
INTEGER(i4) :: i,j,f,kq,m,k,s,nd,d0,r0,nkq,nce,g
REAL(r8) :: tmp,x(3,3)
REAL(r8), CONTIGUOUS, POINTER :: tabt(:,:)
nce=self%nce
nkq=nlc*self%nqp
tabt=>self%q(iq)%reft
!---Logical fluxes
IF(self%q(iq)%xform==qc_xform_none)THEN
  DO f=1,nfld
    DO m=1,self%nqp
      lf(m,f)=flux(1,m,f)
    END DO
  END DO
ELSE
  DO m=1,self%nqp
    g=self%geom%goff(cell)+(m-1)*self%geom%gstride(cell)
    IF(self%q(iq)%xform==qc_xform_gop)THEN
      x=self%geom%gop(:,:,g)
    ELSE
      x=self%geom%cgop(:,:,g)
    END IF
    k=(m-1)*nlc
    DO f=1,nfld
      lf(k+1,f)=x(1,1)*flux(1,m,f)+x(2,1)*flux(2,m,f)+x(3,1)*flux(3,m,f)
      lf(k+2,f)=x(1,2)*flux(1,m,f)+x(2,2)*flux(2,m,f)+x(3,2)*flux(3,m,f)
      lf(k+3,f)=x(1,3)*flux(1,m,f)+x(2,3)*flux(2,m,f)+x(3,3)*flux(3,m,f)
    END DO
  END DO
END IF
!---Contract with canonical table (unit-stride dot products with the transposed table)
DO f=1,nfld
  DO j=1,nce
    tmp=0.d0
    !$omp simd reduction(+:tmp)
    DO kq=1,nkq
      tmp=tmp+tabt(kq,j)*lf(kq,f)
    END DO
    rw(j,f)=tmp
  END DO
END DO
!---Map to cell DOFs (kind 3 entities are skipped and computed below)
CALL qcache_from_canon(self,cell,rw,res,nfld)
IF(self%nxf(3)>0)THEN
  DO i=1,self%nent
    IF(self%ent_orient(i)==0)CYCLE
    s=self%geom%orient(self%ent_orient(i),cell)
    IF(self%xf_kind(s,i)/=3)CYCLE
    nd=self%ent_ndof(i); d0=self%ent_dof0(i); r0=self%ent_row0(s,i)
    DO f=1,nfld
      DO j=1,nd
        tmp=0.d0
        !$omp simd reduction(+:tmp)
        DO kq=1,nkq
          tmp=tmp+tabt(kq,r0+j)*lf(kq,f)
        END DO
        res(d0+j,f)=res(d0+j,f)+tmp
      END DO
    END DO
  END DO
END IF
END SUBROUTINE qcache_accum_cell_kernel
!------------------------------------------------------------------------------
!> Map cell-frame coefficients to the canonical frame, `cw = M^T c` (kind 3 entities set to 0)
!------------------------------------------------------------------------------
SUBROUTINE qcache_to_canon(self,cell,c,cw,nfld)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: cell !< Cell index
REAL(r8), CONTIGUOUS, INTENT(in) :: c(:,:) !< Cell-frame vectors [nce,nfld]
REAL(r8), INTENT(out) :: cw(:,:) !< Canonical-frame vectors [nce,nfld]
INTEGER(i4), INTENT(in) :: nfld !< Number of vectors
INTEGER(i4) :: i,s,nd,d0,o,ro,j,r,f,kind
REAL(r8) :: acc
cw(1:self%nce,1:nfld)=0.d0
DO i=1,self%nent
  nd=self%ent_ndof(i)
  d0=self%ent_dof0(i)
  kind=0
  IF(self%ent_orient(i)>0)THEN
    s=self%geom%orient(self%ent_orient(i),cell)
    kind=self%xf_kind(s,i)
    o=self%xf_off(s,i)
  END IF
  SELECT CASE(kind)
  CASE(0)
    DO f=1,nfld
      DO j=1,nd
        cw(d0+j,f)=cw(d0+j,f)+c(d0+j,f)
      END DO
    END DO
  CASE(1)
    DO f=1,nfld
      DO j=1,nd
        cw(d0+self%xf_perm(o+j),f)=cw(d0+self%xf_perm(o+j),f)+self%xf_sgn(o+j)*c(d0+j,f)
      END DO
    END DO
  CASE(2)
    ro=self%xf_roff(s,i)
    DO f=1,nfld
      DO r=1,self%xf_nreg(s,i)
        acc=0.d0
        DO j=1,nd
          acc=acc+self%xf_mat(o+(r-1)*nd+j)*c(d0+j,f)
        END DO
        cw(self%xf_reg(ro+r),f)=cw(self%xf_reg(ro+r),f)+acc
      END DO
    END DO
  END SELECT
END DO
END SUBROUTINE qcache_to_canon
!------------------------------------------------------------------------------
!> Add canonical-frame results to cell-frame results, `res = res + M rw` (kind 3 entities skipped)
!------------------------------------------------------------------------------
SUBROUTINE qcache_from_canon(self,cell,rw,res,nfld)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: cell !< Cell index
REAL(r8), INTENT(in) :: rw(:,:) !< Canonical-frame vectors [nce,nfld]
REAL(r8), CONTIGUOUS, INTENT(inout) :: res(:,:) !< Cell-frame vectors [nce,nfld]
INTEGER(i4), INTENT(in) :: nfld !< Number of vectors
INTEGER(i4) :: i,s,nd,d0,o,ro,j,r,f,kind
REAL(r8) :: acc
DO i=1,self%nent
  nd=self%ent_ndof(i)
  d0=self%ent_dof0(i)
  kind=0
  IF(self%ent_orient(i)>0)THEN
    s=self%geom%orient(self%ent_orient(i),cell)
    kind=self%xf_kind(s,i)
    o=self%xf_off(s,i)
  END IF
  SELECT CASE(kind)
  CASE(0)
    DO f=1,nfld
      DO j=1,nd
        res(d0+j,f)=res(d0+j,f)+rw(d0+j,f)
      END DO
    END DO
  CASE(1)
    DO f=1,nfld
      DO j=1,nd
        res(d0+j,f)=res(d0+j,f)+self%xf_sgn(o+j)*rw(d0+self%xf_perm(o+j),f)
      END DO
    END DO
  CASE(2)
    ro=self%xf_roff(s,i)
    DO f=1,nfld
      DO r=1,self%xf_nreg(s,i)
        acc=rw(self%xf_reg(ro+r),f)
        DO j=1,nd
          res(d0+j,f)=res(d0+j,f)+self%xf_mat(o+(r-1)*nd+j)*acc
        END DO
      END DO
    END DO
  END SELECT
END DO
END SUBROUTINE qcache_from_canon
