CONTAINS
!------------------------------------------------------------------------------
!> Flag cells that share a vertex with a cell in another thread partition (`mesh%%tloc_c`)
!!
!! Every DOF of a cell lives on its vertices, edges, faces or interior, so contributions of an
!! unflagged cell touch only DOFs that no other partition touches and can be scattered without
!! synchronization. Flagged cells need atomic (or locked) updates.
!------------------------------------------------------------------------------
SUBROUTINE fem_cell_shared_flags(mesh,flags)
CLASS(oft_mesh), INTENT(in) :: mesh !< Mesh
LOGICAL, INTENT(out) :: flags(:) !< Shared flag for each cell [mesh%nc]
INTEGER(i4) :: i,ii,ip,j,k
INTEGER(i4), ALLOCATABLE, DIMENSION(:) :: cpart
DEBUG_STACK_PUSH
!---Partition index of each cell
ALLOCATE(cpart(mesh%nc))
cpart=0
DO ip=1,mesh%nparts
  DO ii=1,mesh%tloc_c(ip)%n
    cpart(mesh%tloc_c(ip)%v(ii))=ip
  END DO
END DO
!---Flag cells with a vertex neighbor in another partition
!$omp parallel do private(j,k)
DO i=1,mesh%nc
  flags(i)=.FALSE.
  DO k=1,mesh%cell_np
    j=mesh%lc(k,i)
    IF(ANY(cpart(mesh%lpc(mesh%kpc(j):mesh%kpc(j+1)-1))/=cpart(i)))THEN
      flags(i)=.TRUE.
      EXIT
    END IF
  END DO
END DO
DEALLOCATE(cpart)
DEBUG_STACK_POP
END SUBROUTINE fem_cell_shared_flags
!------------------------------------------------------------------------------
!> Build geometry cache for a mesh and quadrature rule
!!
!! Cells for which \ref oft_mesh_type::cell_is_curved "cell_is_curved" is false use the Jacobian
!! at the first quadrature point for all points (as the xMHD kernels do). Other cells (curved
!! tets, all hexes) are tested: if `gop` and `det` at every point agree with the first point to
!! within `affine_tol` (relative), one entry is stored, otherwise one entry per point.
!------------------------------------------------------------------------------
SUBROUTINE qcache_geom_setup(self,mesh,quad,store_pts,store_shared,affine_tol)
CLASS(oft_qcache_geom), INTENT(inout) :: self !< Geometry cache
CLASS(oft_mesh), POINTER, INTENT(in) :: mesh !< Mesh
TYPE(oft_quad_type), INTENT(in) :: quad !< Quadrature rule
LOGICAL, OPTIONAL, INTENT(in) :: store_pts !< Store physical quadrature points? (default: F)
LOGICAL, OPTIONAL, INTENT(in) :: store_shared !< Store thread-partition boundary flags? (default: F)
REAL(r8), OPTIONAL, INTENT(in) :: affine_tol !< Relative tolerance for constant-Jacobian detection (default: 1E-14)
INTEGER(i4) :: i,j,k,m,g,nm
REAL(r8) :: tol,gop0(3,4),gopm(3,4),det0,detm,cgtmp(3,6),scale
LOGICAL :: do_pts,do_shared
TYPE(oft_timer) :: mytimer
DEBUG_STACK_PUSH
CALL mytimer%tick
CALL self%delete
do_pts=.FALSE.
IF(PRESENT(store_pts))do_pts=store_pts
do_shared=.FALSE.
IF(PRESENT(store_shared))do_shared=store_shared
tol=1.d-14
IF(PRESENT(affine_tol))tol=affine_tol
!---Sizes
self%mesh=>mesh
self%nc=mesh%nc
self%nqp=quad%np
self%ne=mesh%cell_ne
self%nf=mesh%cell_nf
self%nfs=2*mesh%face_np
IF(mesh%type==3)THEN
  self%nlog=3
  self%ncurl=3
  self%hc(1:3)=(/1,2,4/)
ELSE
  self%nlog=4
  self%ncurl=6
  self%hc=(/1,2,3,4,5,6/)
END IF
ALLOCATE(self%pts(SIZE(quad%pts,DIM=1),self%nqp),self%wts(self%nqp))
self%pts=quad%pts(:,1:self%nqp)
self%wts=quad%wts(1:self%nqp)
!---Find cells with varying geometry
ALLOCATE(self%goff(self%nc),self%gstride(self%nc))
!$omp parallel do private(m,gop0,gopm,det0,detm,scale) schedule(dynamic,64)
DO i=1,self%nc
  self%gstride(i)=0
  IF(.NOT.cell_is_curved(mesh,i))CYCLE
  gop0=0.d0
  CALL mesh%jacobian(i,self%pts(:,1),gop0,det0)
  scale=MAXVAL(ABS(gop0(:,1:self%nlog)))
  DO m=2,self%nqp
    gopm=0.d0
    CALL mesh%jacobian(i,self%pts(:,m),gopm,detm)
    IF((MAXVAL(ABS(gopm(:,1:self%nlog)-gop0(:,1:self%nlog)))>tol*scale) &
      .OR.(ABS(detm-det0)>tol*ABS(det0)))THEN
      self%gstride(i)=1
      EXIT
    END IF
  END DO
END DO
!---Offsets
g=1
DO i=1,self%nc
  self%goff(i)=g
  g=g+1+self%gstride(i)*(self%nqp-1)
END DO
self%ngeom=g-1
self%nvar=SUM(self%gstride)
!---Geometry
ALLOCATE(self%gop(3,self%nlog,self%ngeom),self%cgop(3,self%ncurl,self%ngeom),self%det(self%ngeom))
!$omp parallel do private(m,g,nm,gopm,detm,cgtmp,k) schedule(dynamic,64)
DO i=1,self%nc
  nm=1+self%gstride(i)*(self%nqp-1)
  DO m=1,nm
    g=self%goff(i)+m-1
    gopm=0.d0
    CALL mesh%jacobian(i,self%pts(:,m),gopm,detm)
    CALL oft_hcurl_get_cgops(gopm,cgtmp)
    self%gop(:,:,g)=gopm(:,1:self%nlog)
    DO k=1,self%ncurl
      self%cgop(:,k,g)=cgtmp(:,self%hc(k))
    END DO
    self%det(g)=detm
  END DO
END DO
!---Orientation states
ALLOCATE(self%orient(self%ne+self%nf,self%nc))
!$omp parallel do private(j)
DO i=1,self%nc
  DO j=1,self%ne
    IF(mesh%lce(j,i)<0)THEN
      self%orient(j,i)=2
    ELSE
      self%orient(j,i)=1
    END IF
  END DO
  DO j=1,self%nf
    self%orient(self%ne+j,i)=qcache_face_state(mesh%lcfo(j,i),mesh%face_np)
  END DO
END DO
!---Physical points (eg. for spatially varying coefficients)
IF(do_pts)THEN
  ALLOCATE(self%pt(3,self%nqp,self%nc))
  !$omp parallel do private(m)
  DO i=1,self%nc
    DO m=1,self%nqp
      self%pt(:,m,i)=mesh%log2phys(i,self%pts(:,m))
    END DO
  END DO
END IF
!---Thread partition boundary flags
IF(do_shared)THEN
  ALLOCATE(self%cell_shared(self%nc))
  CALL fem_cell_shared_flags(mesh,self%cell_shared)
END IF
self%setup_time=mytimer%tock()
DEBUG_STACK_POP
END SUBROUTINE qcache_geom_setup
!------------------------------------------------------------------------------
!> Map a face orientation code (`mesh%%lcfo`, \f$ \pm 1..n \f$) to a state index (1..2n)
!------------------------------------------------------------------------------
PURE FUNCTION qcache_face_state(code,np) RESULT(state)
INTEGER(i4), INTENT(in) :: code !< Orientation code
INTEGER(i4), INTENT(in) :: np !< Points per face
INTEGER(i4) :: state
IF(code>0)THEN
  state=code
ELSE
  state=np-code
END IF
END FUNCTION qcache_face_state
!------------------------------------------------------------------------------
!> Inverse of \ref qcache_face_state
!------------------------------------------------------------------------------
PURE FUNCTION qcache_face_code(state,np) RESULT(code)
INTEGER(i4), INTENT(in) :: state !< State index
INTEGER(i4), INTENT(in) :: np !< Points per face
INTEGER(i4) :: code
IF(state<=np)THEN
  code=state
ELSE
  code=np-state
END IF
END FUNCTION qcache_face_code
!------------------------------------------------------------------------------
!> Free geometry cache (safe to call on an object that was never set up)
!------------------------------------------------------------------------------
SUBROUTINE qcache_geom_delete(self)
CLASS(oft_qcache_geom), INTENT(inout) :: self !< Geometry cache
IF(ASSOCIATED(self%pts))DEALLOCATE(self%pts)
IF(ASSOCIATED(self%wts))DEALLOCATE(self%wts)
IF(ASSOCIATED(self%goff))DEALLOCATE(self%goff)
IF(ASSOCIATED(self%gstride))DEALLOCATE(self%gstride)
IF(ASSOCIATED(self%gop))DEALLOCATE(self%gop)
IF(ASSOCIATED(self%cgop))DEALLOCATE(self%cgop)
IF(ASSOCIATED(self%det))DEALLOCATE(self%det)
IF(ASSOCIATED(self%orient))DEALLOCATE(self%orient)
IF(ASSOCIATED(self%pt))DEALLOCATE(self%pt)
IF(ASSOCIATED(self%cell_shared))DEALLOCATE(self%cell_shared)
NULLIFY(self%mesh)
self%nc=0; self%nqp=0; self%ngeom=0; self%nvar=0
END SUBROUTINE qcache_geom_delete
!------------------------------------------------------------------------------
!> Memory used by geometry cache
!------------------------------------------------------------------------------
FUNCTION qcache_geom_mem(self) RESULT(nbytes)
CLASS(oft_qcache_geom), INTENT(in) :: self !< Geometry cache
INTEGER(i8) :: nbytes !< Memory [bytes]
nbytes=0
IF(ASSOCIATED(self%pts))nbytes=nbytes+8_i8*SIZE(self%pts,KIND=i8)
IF(ASSOCIATED(self%wts))nbytes=nbytes+8_i8*SIZE(self%wts,KIND=i8)
IF(ASSOCIATED(self%goff))nbytes=nbytes+4_i8*SIZE(self%goff,KIND=i8)
IF(ASSOCIATED(self%gstride))nbytes=nbytes+4_i8*SIZE(self%gstride,KIND=i8)
IF(ASSOCIATED(self%gop))nbytes=nbytes+8_i8*SIZE(self%gop,KIND=i8)
IF(ASSOCIATED(self%cgop))nbytes=nbytes+8_i8*SIZE(self%cgop,KIND=i8)
IF(ASSOCIATED(self%det))nbytes=nbytes+8_i8*SIZE(self%det,KIND=i8)
IF(ASSOCIATED(self%orient))nbytes=nbytes+4_i8*SIZE(self%orient,KIND=i8)
IF(ASSOCIATED(self%pt))nbytes=nbytes+8_i8*SIZE(self%pt,KIND=i8)
IF(ASSOCIATED(self%cell_shared))nbytes=nbytes+4_i8*SIZE(self%cell_shared,KIND=i8)
END FUNCTION qcache_geom_mem
!------------------------------------------------------------------------------
!> Geometry entry index for (cell, qp)
!------------------------------------------------------------------------------
PURE FUNCTION fem_qcache_geom_index(geom,cell,qp) RESULT(g)
TYPE(oft_qcache_geom), INTENT(in) :: geom !< Geometry cache
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: qp !< Quadrature point index
INTEGER(i4) :: g
g=geom%goff(cell)+(qp-1)*geom%gstride(cell)
END FUNCTION fem_qcache_geom_index
!------------------------------------------------------------------------------
!> Get geometry at (cell, qp) in the format of `mesh%%jacobian` and
!! \ref oft_hcurl_basis::oft_hcurl_get_cgops "oft_hcurl_get_cgops"
!!
!! Unused columns (`gop(:,4)` and `cgop(:,3/5/6)` for hexes) are set to zero.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_geom_get(geom,cell,qp,gop,detw,cgop)
TYPE(oft_qcache_geom), INTENT(in) :: geom !< Geometry cache
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: qp !< Quadrature point index
REAL(r8), INTENT(out) :: gop(3,4) !< Logical gradient vectors
REAL(r8), INTENT(out) :: detw !< Jacobian determinant times quadrature weight
REAL(r8), OPTIONAL, INTENT(out) :: cgop(3,6) !< Cross products of `gop`
INTEGER(i4) :: g,k
g=geom%goff(cell)+(qp-1)*geom%gstride(cell)
IF(geom%nlog<4)gop(:,4)=0.d0
gop(:,1:geom%nlog)=geom%gop(:,:,g)
detw=geom%det(g)*geom%wts(qp)
IF(PRESENT(cgop))THEN
  IF(geom%ncurl<6)cgop=0.d0
  DO k=1,geom%ncurl
    cgop(:,geom%hc(k))=geom%cgop(:,k,g)
  END DO
END IF
END SUBROUTINE fem_qcache_geom_get
!------------------------------------------------------------------------------
!> Build quadrature-point basis cache for an FE space
!!
!! Supported spaces are 3D Lagrange (\ref oft_lag_basis::oft_scalar_fem "oft_scalar_fem"),
!! \f$ H^1 \f$ (\ref oft_h1_basis::oft_h1_fem "oft_h1_fem") and H(Curl)
!! (\ref oft_hcurl_basis::oft_hcurl_fem "oft_hcurl_fem"). Default quantities are values and
!! gradients for Lagrange, gradients for \f$ H^1 \f$, and values and curls for H(Curl).
!!
!! The FE space may be of any order on the mesh of `geom`, eg. a coarse p-level evaluated at the
!! finest level's quadrature points. Must not be called from inside an OpenMP parallel region.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_setup(self,fe,geom,mode,need_val,need_grad,need_curl)
CLASS(oft_fem_qcache), INTENT(inout) :: self !< Basis cache
CLASS(oft_afem_type), TARGET, INTENT(in) :: fe !< FE space
TYPE(oft_qcache_geom), TARGET, INTENT(in) :: geom !< Geometry cache (same mesh)
INTEGER(i4), INTENT(in) :: mode !< Cache mode (`qcache_mode_full` or `qcache_mode_ref`)
LOGICAL, OPTIONAL, INTENT(in) :: need_val !< Cache values?
LOGICAL, OPTIONAL, INTENT(in) :: need_grad !< Cache gradients (Lagrange, \f$ H^1 \f$)?
LOGICAL, OPTIONAL, INTENT(in) :: need_curl !< Cache curls (H(Curl))?
LOGICAL :: needs(3)
INTEGER(i4) :: i,j,s,nv,row
TYPE(oft_timer) :: mytimer
DEBUG_STACK_PUSH
CALL mytimer%tick
CALL self%delete
IF(geom%nc==0)CALL oft_abort('Geometry cache not set up','fem_qcache_setup',__FILE__)
!---Identify basis
SELECT TYPE(fe)
  CLASS IS(oft_scalar_fem)
    self%basis=qcache_basis_lag
    self%fe=>fe
    needs=(/.TRUE.,.TRUE.,.FALSE./)
  CLASS IS(oft_h1_fem)
    self%basis=qcache_basis_h1
    self%fe=>fe
    needs=(/.FALSE.,.TRUE.,.FALSE./)
  CLASS IS(oft_hcurl_fem)
    self%basis=qcache_basis_hcurl
    self%fe=>fe
    needs=(/.TRUE.,.FALSE.,.TRUE./)
  CLASS DEFAULT
    CALL oft_abort('Unsupported FE type','fem_qcache_setup',__FILE__)
END SELECT
IF(.NOT.ASSOCIATED(self%fe%mesh,geom%mesh))CALL oft_abort('FE space and geometry use different meshes', &
  'fem_qcache_setup',__FILE__)
IF(PRESENT(need_val))needs(1)=need_val
IF(PRESENT(need_grad))needs(2)=need_grad
IF(PRESENT(need_curl))needs(3)=need_curl
IF(self%basis==qcache_basis_hcurl)needs(2)=.FALSE.
IF(self%basis/=qcache_basis_hcurl)needs(3)=.FALSE.
self%geom=>geom
self%nce=self%fe%nce
self%nqp=geom%nqp
self%nc=geom%nc
!---Quantity descriptors
IF(needs(qcache_val))THEN
  IF(self%basis==qcache_basis_hcurl)THEN
    self%q(qcache_val)%xform=qc_xform_gop
    self%q(qcache_val)%nlc=geom%nlog
    self%q(qcache_val)%npc=3
  ELSE
    self%q(qcache_val)%xform=qc_xform_none
    self%q(qcache_val)%nlc=1
    self%q(qcache_val)%npc=1
  END IF
END IF
IF(needs(qcache_grad))THEN
  self%q(qcache_grad)%xform=qc_xform_gop
  self%q(qcache_grad)%nlc=geom%nlog
  self%q(qcache_grad)%npc=3
END IF
IF(needs(qcache_curl))THEN
  self%q(qcache_curl)%xform=qc_xform_cgop
  self%q(qcache_curl)%nlc=geom%ncurl
  self%q(qcache_curl)%npc=3
END IF
!---Entity structure (vertices, edges, faces, cell)
nv=self%fe%mesh%cell_np
self%nent=nv+geom%ne+geom%nf+1
self%nstmax=MAX(2,geom%nfs)
ALLOCATE(self%ent_ndof(self%nent),self%ent_dof0(self%nent),self%ent_orient(self%nent))
ALLOCATE(self%ent_nst(self%nent),self%ent_row0(self%nstmax,self%nent))
self%ent_orient=0
self%ent_nst=1
DO i=1,nv
  self%ent_ndof(i)=self%fe%gstruct(1)
END DO
DO i=1,geom%ne
  self%ent_ndof(nv+i)=self%fe%gstruct(2)
  self%ent_orient(nv+i)=i
  self%ent_nst(nv+i)=2
END DO
DO i=1,geom%nf
  self%ent_ndof(nv+geom%ne+i)=self%fe%gstruct(3)
  self%ent_orient(nv+geom%ne+i)=geom%ne+i
  self%ent_nst(nv+geom%ne+i)=geom%nfs
END DO
self%ent_ndof(self%nent)=self%fe%gstruct(4)
IF(SUM(self%ent_ndof)/=self%nce)CALL oft_abort('Inconsistent DOF structure','fem_qcache_setup',__FILE__)
j=0; row=0
self%ent_row0=-1
DO i=1,self%nent
  self%ent_dof0(i)=j
  j=j+self%ent_ndof(i)
  DO s=1,self%ent_nst(i)
    self%ent_row0(s,i)=row
    row=row+self%ent_ndof(i)
  END DO
END DO
self%nrows=row
!---Build tables
self%mode=mode
SELECT CASE(mode)
  CASE(qcache_mode_full)
    CALL qcache_build_full(self)
  CASE(qcache_mode_ref)
    CALL qcache_build_ref(self)
  CASE DEFAULT
    CALL oft_abort('Unknown cache mode','fem_qcache_setup',__FILE__)
END SELECT
self%setup_time=mytimer%tock()
DEBUG_STACK_POP
END SUBROUTINE fem_qcache_setup
!------------------------------------------------------------------------------
!> Evaluate one physical quantity for all DOFs of a cell with the standard evaluators
!------------------------------------------------------------------------------
SUBROUTINE qcache_eval_direct(fe,basis,iq,cell,f,gop,cgop,rop1,rop3,out)
CLASS(oft_fem_type), INTENT(in) :: fe !< FE space
INTEGER(i4), INTENT(in) :: basis !< Basis kind
INTEGER(i4), INTENT(in) :: iq !< Quantity
INTEGER(i4), INTENT(in) :: cell !< Cell
REAL(r8), INTENT(in) :: f(:) !< Logical position
REAL(r8), INTENT(in) :: gop(3,4) !< Logical gradient vectors
REAL(r8), INTENT(in) :: cgop(3,6) !< Cross products of `gop`
REAL(r8), CONTIGUOUS, INTENT(inout) :: rop1(:) !< Work array [nce]
REAL(r8), CONTIGUOUS, INTENT(inout) :: rop3(:,:) !< Work array [3,nce]
REAL(r8), INTENT(out) :: out(:,:) !< Result [nce,1 or 3]
INTEGER(i4) :: j
SELECT TYPE(fe)
  CLASS IS(oft_scalar_fem)
    IF(iq==qcache_val)THEN
      CALL oft_lag_eval_all(fe,cell,f,rop1)
      out(:,1)=rop1
      RETURN
    ELSE
      CALL oft_lag_geval_all(fe,cell,f,rop3,gop)
    END IF
  CLASS IS(oft_h1_fem)
    IF(iq==qcache_val)THEN
      CALL oft_h1_eval_all(fe,cell,f,rop1)
      out(:,1)=rop1
      RETURN
    ELSE
      CALL oft_h1_geval_all(fe,cell,f,rop3,gop)
    END IF
  CLASS IS(oft_hcurl_fem)
    IF(iq==qcache_val)THEN
      CALL oft_hcurl_eval_all(fe,cell,f,rop3,gop)
    ELSE
      CALL oft_hcurl_ceval_all(fe,cell,f,rop3,cgop)
    END IF
END SELECT
DO j=1,3
  out(:,j)=rop3(j,:)
END DO
END SUBROUTINE qcache_eval_direct
!------------------------------------------------------------------------------
!> Build FULL mode tables using the standard evaluators and cached geometry
!------------------------------------------------------------------------------
SUBROUTINE qcache_build_full(self)
CLASS(oft_fem_qcache), INTENT(inout) :: self !< Basis cache
INTEGER(i4) :: i,m,iq
REAL(r8) :: gop(3,4),cgop(3,6),detw
REAL(r8), ALLOCATABLE, DIMENSION(:) :: rop1
REAL(r8), ALLOCATABLE, DIMENSION(:,:) :: rop3
DO iq=1,3
  IF(self%q(iq)%xform<0)CYCLE
  ALLOCATE(self%q(iq)%full(self%nce,self%q(iq)%npc,self%nqp,self%nc))
END DO
!$omp parallel private(i,m,iq,gop,cgop,detw,rop1,rop3)
ALLOCATE(rop1(self%nce),rop3(3,self%nce))
!$omp do schedule(dynamic,16)
DO i=1,self%nc
  DO m=1,self%nqp
    CALL fem_qcache_geom_get(self%geom,i,m,gop,detw,cgop)
    DO iq=1,3
      IF(self%q(iq)%xform<0)CYCLE
      CALL qcache_eval_direct(self%fe,self%basis,iq,i,self%geom%pts(:,m),gop,cgop,rop1,rop3, &
        self%q(iq)%full(:,:,m,i))
    END DO
  END DO
END DO
DEALLOCATE(rop1,rop3)
!$omp end parallel
END SUBROUTINE qcache_build_full
!------------------------------------------------------------------------------
!> Build REFERENCE mode tables
!!
!! The logical components of each basis function are extracted from the standard evaluators
!! using unit `gop`/`cgop` columns (the evaluators are linear in them). Evaluation is done on
!! an internal template mesh with `max(2,2*face_np)` cells: template cell `s` has all edges in
!! state `min(s,2)` (state 1: `lce>0`, state 2: `lce<0`) and all faces in state `s`. The FE
!! object is shallow-copied with its mesh pointer replaced, so the user's objects are not
!! modified.
!------------------------------------------------------------------------------
SUBROUTINE qcache_build_ref(self)
CLASS(oft_fem_qcache), INTENT(inout) :: self !< Basis cache
CLASS(oft_mesh), POINTER :: tmesh
CLASS(oft_fem_type), POINTER :: tfe
INTEGER(i4) :: i,iq,s,m,e,ns,np,nlog,ncurl,ipass,k,idx,j,row0,nd,d0
INTEGER(i4) :: hc(6)
REAL(r8) :: gopu(3,4),cgopu(3,6)
REAL(r8), ALLOCATABLE, DIMENSION(:) :: rop1
REAL(r8), ALLOCATABLE, DIMENSION(:,:) :: rop3,lt,ls
DO iq=1,3
  IF(self%q(iq)%xform<0)CYCLE
  ALLOCATE(self%q(iq)%ref(self%nrows,self%q(iq)%nlc,self%nqp))
  self%q(iq)%ref=0.d0
END DO
nlog=self%geom%nlog
ncurl=self%geom%ncurl
hc=self%geom%hc
np=self%fe%mesh%face_np
ns=self%nstmax
!---Orientation template mesh
ALLOCATE(tmesh,MOLD=self%fe%mesh)
tmesh%type=self%fe%mesh%type
tmesh%cell_np=self%fe%mesh%cell_np
tmesh%cell_ne=self%fe%mesh%cell_ne
tmesh%cell_nf=self%fe%mesh%cell_nf
tmesh%face_np=self%fe%mesh%face_np
tmesh%nc=ns
tmesh%cell_ed=>self%fe%mesh%cell_ed
tmesh%cell_fc=>self%fe%mesh%cell_fc
ALLOCATE(tmesh%lce(tmesh%cell_ne,ns),tmesh%lcfo(tmesh%cell_nf,ns))
DO s=1,ns
  DO e=1,tmesh%cell_ne
    tmesh%lce(e,s)=e
    IF(s==2)tmesh%lce(e,s)=-e
  END DO
  tmesh%lcfo(:,s)=qcache_face_code(MIN(s,self%geom%nfs),np)
END DO
ALLOCATE(tfe,SOURCE=self%fe)
tfe%mesh=>tmesh
!---Evaluate on template cells (serial; reset orientation cache of standard evaluators)
oriented_cell=-1
ALLOCATE(rop1(self%nce),rop3(3,self%nce),lt(self%nce,6),ls(self%nce,3))
gopu=0.d0
cgopu=0.d0
DO s=1,ns
  DO m=1,self%nqp
    DO iq=1,3
      IF(self%q(iq)%xform<0)CYCLE
      !---Logical components lt(:,1:nlc)
      SELECT CASE(self%q(iq)%xform)
        CASE(qc_xform_none)
          CALL qcache_eval_direct(tfe,self%basis,iq,s,self%geom%pts(:,m),gopu,cgopu,rop1,rop3,lt(:,1:1))
        CASE(qc_xform_gop)
          DO ipass=0,(nlog-1)/3
            gopu=0.d0
            DO k=1,3
              idx=3*ipass+k
              IF(idx<=nlog)gopu(k,idx)=1.d0
            END DO
            CALL qcache_eval_direct(tfe,self%basis,iq,s,self%geom%pts(:,m),gopu,cgopu,rop1,rop3,ls)
            DO k=1,3
              idx=3*ipass+k
              IF(idx<=nlog)lt(:,idx)=ls(:,k)
            END DO
          END DO
        CASE(qc_xform_cgop)
          DO ipass=0,(ncurl-1)/3
            cgopu=0.d0
            DO k=1,3
              idx=3*ipass+k
              IF(idx<=ncurl)cgopu(k,hc(idx))=1.d0
            END DO
            CALL qcache_eval_direct(tfe,self%basis,iq,s,self%geom%pts(:,m),gopu,cgopu,rop1,rop3,ls)
            DO k=1,3
              idx=3*ipass+k
              IF(idx<=ncurl)lt(:,idx)=ls(:,k)
            END DO
          END DO
      END SELECT
      !---Store blocks of entities whose state is represented by template cell s
      DO i=1,self%nent
        nd=self%ent_ndof(i)
        IF(nd==0)CYCLE
        IF(s>self%ent_nst(i))CYCLE
        row0=self%ent_row0(s,i)
        d0=self%ent_dof0(i)
        DO k=1,self%q(iq)%nlc
          DO j=1,nd
            self%q(iq)%ref(row0+j,k,m)=lt(d0+j,k)
          END DO
        END DO
      END DO
    END DO
  END DO
END DO
oriented_cell=-1
DEALLOCATE(rop1,rop3,lt,ls)
!---Free template objects (pointer components are shared and must not be freed)
NULLIFY(tfe%mesh)
DEALLOCATE(tfe)
DEALLOCATE(tmesh%lce,tmesh%lcfo)
NULLIFY(tmesh%cell_ed,tmesh%cell_fc)
DEALLOCATE(tmesh)
END SUBROUTINE qcache_build_ref
!------------------------------------------------------------------------------
!> Free basis cache (safe to call on an object that was never set up)
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_delete(self)
CLASS(oft_fem_qcache), INTENT(inout) :: self !< Basis cache
INTEGER(i4) :: iq
DO iq=1,3
  IF(ASSOCIATED(self%q(iq)%ref))DEALLOCATE(self%q(iq)%ref)
  IF(ASSOCIATED(self%q(iq)%full))DEALLOCATE(self%q(iq)%full)
  self%q(iq)%xform=-1
  self%q(iq)%nlc=0
  self%q(iq)%npc=0
END DO
IF(ASSOCIATED(self%ent_ndof))DEALLOCATE(self%ent_ndof)
IF(ASSOCIATED(self%ent_dof0))DEALLOCATE(self%ent_dof0)
IF(ASSOCIATED(self%ent_orient))DEALLOCATE(self%ent_orient)
IF(ASSOCIATED(self%ent_nst))DEALLOCATE(self%ent_nst)
IF(ASSOCIATED(self%ent_row0))DEALLOCATE(self%ent_row0)
NULLIFY(self%fe,self%geom)
self%mode=qcache_mode_none
self%nce=0; self%nqp=0; self%nc=0; self%nrows=0; self%nent=0
END SUBROUTINE fem_qcache_delete
!------------------------------------------------------------------------------
!> Memory used by basis cache (excluding the shared geometry cache)
!------------------------------------------------------------------------------
FUNCTION fem_qcache_mem(self) RESULT(nbytes)
CLASS(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i8) :: nbytes !< Memory [bytes]
INTEGER(i4) :: iq
nbytes=0
DO iq=1,3
  IF(ASSOCIATED(self%q(iq)%ref))nbytes=nbytes+8_i8*SIZE(self%q(iq)%ref,KIND=i8)
  IF(ASSOCIATED(self%q(iq)%full))nbytes=nbytes+8_i8*SIZE(self%q(iq)%full,KIND=i8)
END DO
IF(ASSOCIATED(self%ent_row0))nbytes=nbytes+4_i8*(SIZE(self%ent_row0,KIND=i8)+4_i8*self%nent)
END FUNCTION fem_qcache_mem
!------------------------------------------------------------------------------
!> Is the cache set up?
!------------------------------------------------------------------------------
FUNCTION fem_qcache_ready(self) RESULT(ready)
CLASS(oft_fem_qcache), INTENT(in) :: self !< Basis cache
LOGICAL :: ready
ready=(self%mode/=qcache_mode_none)
END FUNCTION fem_qcache_ready
!------------------------------------------------------------------------------
!> Get reference table rows of all local DOFs of a cell
!!
!! Call once per cell; the result is passed to the per-qp kernels. In FULL mode `rows` is not
!! used by the kernels and this routine sets it to the identity.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_cell_rows(self,cell,rows)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(out) :: rows(:) !< Table row of each local DOF [nce]
INTEGER(i4) :: i,j,s,row0,d0
IF(self%mode/=qcache_mode_ref)THEN
  DO j=1,self%nce
    rows(j)=j
  END DO
  RETURN
END IF
DO i=1,self%nent
  s=1
  IF(self%ent_orient(i)>0)s=self%geom%orient(self%ent_orient(i),cell)
  row0=self%ent_row0(s,i)
  d0=self%ent_dof0(i)
  DO j=1,self%ent_ndof(i)
    rows(d0+j)=row0+j
  END DO
END DO
END SUBROUTINE fem_qcache_cell_rows
!------------------------------------------------------------------------------
!> Evaluate a physical basis quantity for all DOFs at (cell, qp)
!!
!! FULL mode copies the stored block (callers may also use `self%%q(iq)%%full(:,:,qp,cell)`
!! directly); REFERENCE mode rebuilds it from the reference table and cached geometry.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_eval(self,iq,cell,qp,rows,out)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: iq !< Quantity (`qcache_val`, `qcache_grad`, `qcache_curl`)
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: qp !< Quadrature point index
INTEGER(i4), INTENT(in) :: rows(:) !< Table rows from \ref fem_qcache_cell_rows [nce]
REAL(r8), INTENT(out) :: out(:,:) !< Physical quantity [nce,npc]
INTEGER(i4) :: g,j,k,c
REAL(r8) :: x(3,6),l
IF(self%mode==qcache_mode_full)THEN
  out(1:self%nce,1:self%q(iq)%npc)=self%q(iq)%full(:,:,qp,cell)
  RETURN
END IF
g=self%geom%goff(cell)+(qp-1)*self%geom%gstride(cell)
SELECT CASE(self%q(iq)%xform)
  CASE(qc_xform_none)
    DO j=1,self%nce
      out(j,1)=self%q(iq)%ref(rows(j),1,qp)
    END DO
    RETURN
  CASE(qc_xform_gop)
    x(:,1:self%q(iq)%nlc)=self%geom%gop(:,:,g)
  CASE(qc_xform_cgop)
    x(:,1:self%q(iq)%nlc)=self%geom%cgop(:,:,g)
END SELECT
DO j=1,self%nce
  l=self%q(iq)%ref(rows(j),1,qp)
  out(j,1)=l*x(1,1)
  out(j,2)=l*x(2,1)
  out(j,3)=l*x(3,1)
END DO
DO k=2,self%q(iq)%nlc
  DO c=1,3
    DO j=1,self%nce
      out(j,c)=out(j,c)+self%q(iq)%ref(rows(j),k,qp)*x(c,k)
    END DO
  END DO
END DO
END SUBROUTINE fem_qcache_eval
!------------------------------------------------------------------------------
!> Evaluate a physical basis quantity for all DOFs and quadrature points of a cell
!!
!! Produces a `(nce,npc,nqp)` block, eg. as a GEMM operand for local matrix assembly.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_eval_cell(self,iq,cell,out)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: iq !< Quantity (`qcache_val`, `qcache_grad`, `qcache_curl`)
INTEGER(i4), INTENT(in) :: cell !< Cell index
REAL(r8), INTENT(out) :: out(:,:,:) !< Physical quantity [nce,npc,nqp]
INTEGER(i4) :: m,rows(self%nce)
IF(self%mode==qcache_mode_full)THEN
  out(1:self%nce,1:self%q(iq)%npc,1:self%nqp)=self%q(iq)%full(:,:,:,cell)
  RETURN
END IF
CALL fem_qcache_cell_rows(self,cell,rows)
DO m=1,self%nqp
  CALL fem_qcache_eval(self,iq,cell,m,rows,out(:,:,m))
END DO
END SUBROUTINE fem_qcache_eval_cell
!------------------------------------------------------------------------------
!> Reconstruct fields from local DOF coefficients at (cell, qp)
!!
!! Computes `out(c,f) = sum_j coefs(j,f)*phi_j,c` for `nfld` fields at once. In REFERENCE mode
!! the coefficients are contracted with the logical table first and the geometry transform is
!! applied once per field, so the physical basis is never formed.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_interp(self,iq,cell,qp,rows,coefs,nfld,out)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: iq !< Quantity (`qcache_val`, `qcache_grad`, `qcache_curl`)
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: qp !< Quadrature point index
INTEGER(i4), INTENT(in) :: rows(:) !< Table rows from \ref fem_qcache_cell_rows [nce]
INTEGER(i4), INTENT(in) :: nfld !< Number of fields
REAL(r8), INTENT(in) :: coefs(:,:) !< Local DOF coefficients [nce,nfld]
REAL(r8), INTENT(out) :: out(:,:) !< Reconstructed fields [npc,nfld]
INTEGER(i4) :: g,j,k,c,f,nlc,nce
REAL(r8) :: x(3,6),lc(6),tmp
nce=self%nce
IF(self%mode==qcache_mode_full)THEN
  DO f=1,nfld
    DO c=1,self%q(iq)%npc
      tmp=0.d0
      DO j=1,nce
        tmp=tmp+coefs(j,f)*self%q(iq)%full(j,c,qp,cell)
      END DO
      out(c,f)=tmp
    END DO
  END DO
  RETURN
END IF
nlc=self%q(iq)%nlc
g=self%geom%goff(cell)+(qp-1)*self%geom%gstride(cell)
SELECT CASE(self%q(iq)%xform)
  CASE(qc_xform_none)
    DO f=1,nfld
      tmp=0.d0
      DO j=1,nce
        tmp=tmp+coefs(j,f)*self%q(iq)%ref(rows(j),1,qp)
      END DO
      out(1,f)=tmp
    END DO
    RETURN
  CASE(qc_xform_gop)
    x(:,1:nlc)=self%geom%gop(:,:,g)
  CASE(qc_xform_cgop)
    x(:,1:nlc)=self%geom%cgop(:,:,g)
END SELECT
DO f=1,nfld
  DO k=1,nlc
    tmp=0.d0
    DO j=1,nce
      tmp=tmp+coefs(j,f)*self%q(iq)%ref(rows(j),k,qp)
    END DO
    lc(k)=tmp
  END DO
  DO c=1,3
    tmp=0.d0
    DO k=1,nlc
      tmp=tmp+x(c,k)*lc(k)
    END DO
    out(c,f)=tmp
  END DO
END DO
END SUBROUTINE fem_qcache_interp
!------------------------------------------------------------------------------
!> Accumulate a test-function contraction at (cell, qp)
!!
!! Computes `res(j) = res(j) + sum_c phi_j,c * flux(c)` for all local DOFs. In REFERENCE mode
!! the flux is transformed to logical components once, so the physical basis is never formed.
!! Quadrature weights and Jacobian determinants must be included in `flux` by the caller.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_accum(self,iq,cell,qp,rows,flux,res)
TYPE(oft_fem_qcache), INTENT(in) :: self !< Basis cache
INTEGER(i4), INTENT(in) :: iq !< Quantity (`qcache_val`, `qcache_grad`, `qcache_curl`)
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: qp !< Quadrature point index
INTEGER(i4), INTENT(in) :: rows(:) !< Table rows from \ref fem_qcache_cell_rows [nce]
REAL(r8), INTENT(in) :: flux(:) !< Physical flux [npc]
REAL(r8), INTENT(inout) :: res(:) !< Local residual [nce]
INTEGER(i4) :: g,j,k,c,nlc,nce
REAL(r8) :: x(3,6),lf(6),tmp
nce=self%nce
IF(self%mode==qcache_mode_full)THEN
  DO c=1,self%q(iq)%npc
    tmp=flux(c)
    DO j=1,nce
      res(j)=res(j)+self%q(iq)%full(j,c,qp,cell)*tmp
    END DO
  END DO
  RETURN
END IF
nlc=self%q(iq)%nlc
g=self%geom%goff(cell)+(qp-1)*self%geom%gstride(cell)
SELECT CASE(self%q(iq)%xform)
  CASE(qc_xform_none)
    tmp=flux(1)
    DO j=1,nce
      res(j)=res(j)+self%q(iq)%ref(rows(j),1,qp)*tmp
    END DO
    RETURN
  CASE(qc_xform_gop)
    x(:,1:nlc)=self%geom%gop(:,:,g)
  CASE(qc_xform_cgop)
    x(:,1:nlc)=self%geom%cgop(:,:,g)
END SELECT
DO k=1,nlc
  lf(k)=x(1,k)*flux(1)+x(2,k)*flux(2)+x(3,k)*flux(3)
END DO
DO k=1,nlc
  tmp=lf(k)
  DO j=1,nce
    res(j)=res(j)+self%q(iq)%ref(rows(j),k,qp)*tmp
  END DO
END DO
END SUBROUTINE fem_qcache_accum
END MODULE fem_quad_cache
