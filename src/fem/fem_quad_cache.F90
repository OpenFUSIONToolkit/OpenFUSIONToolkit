IF(ASSOCIATED(self%ent_row0))nbytes=nbytes+4_i8*(SIZE(self%ent_row0,KIND=i8)+4_i8*self%nent)
IF(ASSOCIATED(self%xf_kind))nbytes=nbytes+16_i8*SIZE(self%xf_kind,KIND=i8)
IF(ASSOCIATED(self%xf_reg))nbytes=nbytes+4_i8*SIZE(self%xf_reg,KIND=i8)
IF(ASSOCIATED(self%xf_perm))nbytes=nbytes+4_i8*SIZE(self%xf_perm,KIND=i8)
IF(ASSOCIATED(self%xf_sgn))nbytes=nbytes+8_i8*SIZE(self%xf_sgn,KIND=i8)
IF(ASSOCIATED(self%xf_mat))nbytes=nbytes+8_i8*SIZE(self%xf_mat,KIND=i8)
END FUNCTION fem_qcache_mem
