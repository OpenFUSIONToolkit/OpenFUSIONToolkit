!> @file fem_quad_cache.F90
!
!> Precomputed basis and geometry data at quadrature points for 3D FE kernels
!!
!! Two objects are provided:
!! - \ref fem_quad_cache::oft_qcache_geom "oft_qcache_geom": per-mesh/per-quadrature geometry
!!   (logical gradient vectors `gop`, their cross products `cgop`, Jacobian determinants,
!!   per-cell entity orientation codes, and optionally physical quadrature points and
!!   thread-partition boundary flags).
!! - \ref fem_quad_cache::oft_fem_qcache "oft_fem_qcache": basis data for one FE space
!!   (Lagrange, \f$ H^1 \f$ or H(Curl)) on that geometry, stored as cell-independent reference
!!   tables of the logical components of every basis function. Physical values, gradients and
!!   curls are rebuilt on the fly from the tables and the per-cell `gop`/`cgop`, so memory does
!!   not grow with the number of cells beyond the geometry itself.
!!
!! **Design**
!! - *Reference tables indexed by entity orientation.* Every DOF belongs to one entity (vertex,
!!   edge, face or cell interior), and its function depends only on that entity's orientation:
!!   edges have two states (`mesh%%lce` sign) and faces have `2*face_np` states (`mesh%%lcfo`
!!   code). The tables hold one block of rows per (entity, state). They are generated by calling
!!   the standard evaluators on a small internal "orientation template" mesh whose cells
!!   enumerate all states, so they match the evaluators exactly. The per-entity assumption is
!!   checked against direct evaluation on real meshes by `tests/fem/test_fem_qcache`.
!! - *Per-cell geometry.* `gop`, `cgop` and the Jacobian determinant are stored once per cell
!!   for cells with a constant Jacobian (straight tets, affine hexes) and once per (cell, qp)
!!   otherwise, together with the orientation state of every edge and face of the cell.
!! - *Orientation transforms.* For each (entity, state) the setup fits the transform from the
!!   state-1 ("canonical") functions (\ref fem_quad_cache::qcache_build_xform "qcache_build_xform").
!!   On hexes all of them are signed permutations. On tets, Lagrange and edge transforms are
!!   signed permutations, and \f$ H^1 \f$ faces of order >= 4 are dense combinations of the
!!   canonical functions of the face, its edges/vertices and the interior bubbles. H(Curl) faces
!!   on tets (order >= 2) are not in the span of the canonical H(Curl) functions at all (they
!!   differ by gradients, which live in the separate \f$ H^1 \f$ space); they are handled exactly
!!   with their own dense per-orientation table blocks.
!! - *Cell-batched kernels.* \ref fem_quad_cache::fem_qcache_interp_cell "fem_qcache_interp_cell"
!!   and \ref fem_quad_cache::fem_qcache_accum_cell "fem_qcache_accum_cell" map the local
!!   coefficients (or results) of a cell to the canonical frame once, contract them with the
!!   contiguous canonical table for all quadrature points at once (a `nce x (nlc*nqp)` by
!!   `nce x nfld` product), add the per-orientation blocks of entities without a transform, and
!!   apply the per-qp geometry. No per-DOF gathers are needed.
!!
!! Layout and conventions:
!! - Tables are plain contiguous arrays with the DOF (row) index fastest, `ref(row,lcomp,qp)`,
!!   plus the transposed copy `reft(lcomp+nlc*(qp-1),row)` used by the cell-batched kernels.
!! - Logical components follow the existing basis evaluators, folded to 3 independent ones:
!!   physical vector values and gradients are `sum_k L_k gop(:,gc(k))` (`gc=2:4` for tets, where
!!   `gop(:,1)=-(gop(:,2)+gop(:,3)+gop(:,4))`, `gc=1:3` for hexes) and curls are
!!   `sum_k C_k cgop(:,hc(k))` (`hc=4:6` for tets, `1,2,4` for hexes).
!!
!! Kernel routines contain no allocation, type-bound calls or `SELECT TYPE`, use no module or
!! threadprivate state, and are safe to call concurrently from OpenMP threads once setup is
!! complete:
!! - per cell, all qp at once (recommended):
!!   \ref fem_quad_cache::fem_qcache_interp_cell "fem_qcache_interp_cell",
!!   \ref fem_quad_cache::fem_qcache_accum_cell "fem_qcache_accum_cell",
!!   \ref fem_quad_cache::fem_qcache_eval_cell "fem_qcache_eval_cell";
!! - per (cell, qp): \ref fem_quad_cache::fem_qcache_eval "fem_qcache_eval" (basis),
!!   \ref fem_quad_cache::fem_qcache_interp "fem_qcache_interp" (field reconstruction),
!!   \ref fem_quad_cache::fem_qcache_accum "fem_qcache_accum" (test-function accumulation), with
!!   rows from \ref fem_quad_cache::fem_qcache_cell_rows "fem_qcache_cell_rows" (gather), or in
!!   the canonical frame (\ref fem_quad_cache::fem_qcache_coefs_to_ref "fem_qcache_coefs_to_ref",
!!   \ref fem_quad_cache::fem_qcache_res_from_ref "fem_qcache_res_from_ref") where
!!   \ref fem_quad_cache::fem_qcache_canonical_ok "fem_qcache_canonical_ok" holds;
!! - geometry: \ref fem_quad_cache::fem_qcache_geom_get "fem_qcache_geom_get".
!!
!! @authors Chris Hansen
!! @date November 2026
!! @ingroup doxy_oft_fem
!------------------------------------------------------------------------------
