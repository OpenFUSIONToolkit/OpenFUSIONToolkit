!------------------------------------------------------------------------------
!> Get geometry at (cell, qp) in the format of `mesh%%jacobian` and
!! \ref oft_hcurl_basis::oft_hcurl_get_cgops "oft_hcurl_get_cgops"
!!
!! For tets the dependent column is rebuilt as `gop(:,1)=-(gop(:,2)+gop(:,3)+gop(:,4))`, as
!! `mesh%%jacobian` does; for hexes `gop(:,4)` is zero. `cgop` is recomputed from `gop`.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_geom_get(geom,cell,qp,gop,detw,cgop)
TYPE(oft_qcache_geom), INTENT(in) :: geom !< Geometry cache
INTEGER(i4), INTENT(in) :: cell !< Cell index
INTEGER(i4), INTENT(in) :: qp !< Quadrature point index
REAL(r8), INTENT(out) :: gop(3,4) !< Logical gradient vectors
REAL(r8), INTENT(out) :: detw !< Jacobian determinant times quadrature weight
REAL(r8), OPTIONAL, INTENT(out) :: cgop(3,6) !< Cross products of `gop`
INTEGER(i4) :: g,k
g=geom%goff(cell)+(qp-1)*geom%gstride(cell)
gop=0.d0
DO k=1,3
  gop(:,geom%gc(k))=geom%gop(:,k,g)
END DO
IF(geom%gc(1)==2)gop(:,1)=-(gop(:,2)+gop(:,3)+gop(:,4))
detw=geom%det(g)*geom%wts(qp)
IF(PRESENT(cgop))CALL oft_hcurl_get_cgops(gop,cgop)
END SUBROUTINE fem_qcache_geom_get
!------------------------------------------------------------------------------
!> Build quadrature-point basis cache for an FE space
!!
!! Supported spaces are 3D Lagrange (\ref oft_lag_basis::oft_scalar_fem "oft_scalar_fem"),
!! \f$ H^1 \f$ (\ref oft_h1_basis::oft_h1_fem "oft_h1_fem") and H(Curl)
!! (\ref oft_hcurl_basis::oft_hcurl_fem "oft_hcurl_fem"). Default quantities are values and
!! gradients for Lagrange, gradients for \f$ H^1 \f$, and values and curls for H(Curl).
!!
!! The FE space may be of any order on the mesh of `geom`, eg. a coarse p-level evaluated at the
!! finest level's quadrature points. Must not be called from inside an OpenMP parallel region.
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_setup(self,fe,geom,need_val,need_grad,need_curl)
CLASS(oft_fem_qcache), INTENT(inout) :: self !< Basis cache
CLASS(oft_afem_type), TARGET, INTENT(in) :: fe !< FE space
TYPE(oft_qcache_geom), TARGET, INTENT(in) :: geom !< Geometry cache (same mesh)
LOGICAL, OPTIONAL, INTENT(in) :: need_val !< Cache values?
LOGICAL, OPTIONAL, INTENT(in) :: need_grad !< Cache gradients (Lagrange, \f$ H^1 \f$)?
LOGICAL, OPTIONAL, INTENT(in) :: need_curl !< Cache curls (H(Curl))?
LOGICAL :: needs(3)
INTEGER(i4) :: i,j,s,nv,row
TYPE(oft_timer) :: mytimer
DEBUG_STACK_PUSH
CALL mytimer%tick
CALL self%delete
IF(geom%nc==0)CALL oft_abort('Geometry cache not set up','fem_qcache_setup',__FILE__)
!---Identify basis
SELECT TYPE(fe)
  CLASS IS(oft_scalar_fem)
    self%basis=qcache_basis_lag
    self%fe=>fe
    needs=(/.TRUE.,.TRUE.,.FALSE./)
  CLASS IS(oft_h1_fem)
    self%basis=qcache_basis_h1
    self%fe=>fe
    needs=(/.FALSE.,.TRUE.,.FALSE./)
  CLASS IS(oft_hcurl_fem)
    self%basis=qcache_basis_hcurl
    self%fe=>fe
    needs=(/.TRUE.,.FALSE.,.TRUE./)
  CLASS DEFAULT
    CALL oft_abort('Unsupported FE type','fem_qcache_setup',__FILE__)
END SELECT
IF(.NOT.ASSOCIATED(self%fe%mesh,geom%mesh))CALL oft_abort('FE space and geometry use different meshes', &
  'fem_qcache_setup',__FILE__)
IF(PRESENT(need_val))needs(1)=need_val
IF(PRESENT(need_grad))needs(2)=need_grad
IF(PRESENT(need_curl))needs(3)=need_curl
IF(self%basis==qcache_basis_hcurl)needs(2)=.FALSE.
IF(self%basis/=qcache_basis_hcurl)needs(3)=.FALSE.
self%geom=>geom
self%nce=self%fe%nce
self%nqp=geom%nqp
self%nc=geom%nc
!---Quantity descriptors
IF(needs(qcache_val))THEN
  IF(self%basis==qcache_basis_hcurl)THEN
    self%q(qcache_val)%xform=qc_xform_gop
    self%q(qcache_val)%nlc=geom%nlog
    self%q(qcache_val)%npc=3
  ELSE
    self%q(qcache_val)%xform=qc_xform_none
    self%q(qcache_val)%nlc=1
    self%q(qcache_val)%npc=1
  END IF
END IF
IF(needs(qcache_grad))THEN
  self%q(qcache_grad)%xform=qc_xform_gop
  self%q(qcache_grad)%nlc=geom%nlog
  self%q(qcache_grad)%npc=3
END IF
IF(needs(qcache_curl))THEN
  self%q(qcache_curl)%xform=qc_xform_cgop
  self%q(qcache_curl)%nlc=geom%ncurl
  self%q(qcache_curl)%npc=3
END IF
!---Entity structure (vertices, edges, faces, cell)
nv=self%fe%mesh%cell_np
self%nent=nv+geom%ne+geom%nf+1
self%nstmax=MAX(2,geom%nfs)
ALLOCATE(self%ent_ndof(self%nent),self%ent_dof0(self%nent),self%ent_orient(self%nent))
ALLOCATE(self%ent_nst(self%nent),self%ent_row0(self%nstmax,self%nent))
self%ent_orient=0
self%ent_nst=1
DO i=1,nv
  self%ent_ndof(i)=self%fe%gstruct(1)
END DO
DO i=1,geom%ne
  self%ent_ndof(nv+i)=self%fe%gstruct(2)
  self%ent_orient(nv+i)=i
  self%ent_nst(nv+i)=2
END DO
DO i=1,geom%nf
  self%ent_ndof(nv+geom%ne+i)=self%fe%gstruct(3)
  self%ent_orient(nv+geom%ne+i)=geom%ne+i
  self%ent_nst(nv+geom%ne+i)=geom%nfs
END DO
self%ent_ndof(self%nent)=self%fe%gstruct(4)
IF(SUM(self%ent_ndof)/=self%nce)CALL oft_abort('Inconsistent DOF structure','fem_qcache_setup',__FILE__)
j=0
self%ent_row0=-1
DO i=1,self%nent
  self%ent_dof0(i)=j
  self%ent_row0(1,i)=j
  j=j+self%ent_ndof(i)
END DO
row=self%nce
DO i=1,self%nent
  DO s=2,self%ent_nst(i)
    self%ent_row0(s,i)=row
    row=row+self%ent_ndof(i)
  END DO
END DO
self%nrows=row
!---Build tables
CALL qcache_build_ref(self)
CALL qcache_build_xform(self)
self%setup_time=mytimer%tock()
DEBUG_STACK_POP
END SUBROUTINE fem_qcache_setup
!------------------------------------------------------------------------------
!> Evaluate one physical quantity for all DOFs of a cell with the standard evaluators
!------------------------------------------------------------------------------
SUBROUTINE qcache_eval_direct(fe,basis,iq,cell,f,gop,cgop,rop1,rop3,out)
CLASS(oft_fem_type), INTENT(in) :: fe !< FE space
INTEGER(i4), INTENT(in) :: basis !< Basis kind
INTEGER(i4), INTENT(in) :: iq !< Quantity
INTEGER(i4), INTENT(in) :: cell !< Cell
REAL(r8), INTENT(in) :: f(:) !< Logical position
REAL(r8), INTENT(in) :: gop(3,4) !< Logical gradient vectors
REAL(r8), INTENT(in) :: cgop(3,6) !< Cross products of `gop`
REAL(r8), CONTIGUOUS, INTENT(inout) :: rop1(:) !< Work array [nce]
REAL(r8), CONTIGUOUS, INTENT(inout) :: rop3(:,:) !< Work array [3,nce]
REAL(r8), INTENT(out) :: out(:,:) !< Result [nce,1 or 3]
INTEGER(i4) :: j
SELECT TYPE(fe)
  CLASS IS(oft_scalar_fem)
    IF(iq==qcache_val)THEN
      CALL oft_lag_eval_all(fe,cell,f,rop1)
      out(:,1)=rop1
      RETURN
    ELSE
      CALL oft_lag_geval_all(fe,cell,f,rop3,gop)
    END IF
  CLASS IS(oft_h1_fem)
    IF(iq==qcache_val)THEN
      CALL oft_h1_eval_all(fe,cell,f,rop1)
      out(:,1)=rop1
      RETURN
    ELSE
      CALL oft_h1_geval_all(fe,cell,f,rop3,gop)
    END IF
  CLASS IS(oft_hcurl_fem)
    IF(iq==qcache_val)THEN
      CALL oft_hcurl_eval_all(fe,cell,f,rop3,gop)
    ELSE
      CALL oft_hcurl_ceval_all(fe,cell,f,rop3,cgop)
    END IF
END SELECT
DO j=1,3
  out(:,j)=rop3(j,:)
END DO
END SUBROUTINE qcache_eval_direct
!------------------------------------------------------------------------------
!> Build the reference tables
!!
!! The logical components of each basis function are extracted from the standard evaluators
!! using unit `gop`/`cgop` columns (the evaluators are linear in them). Evaluation is done on
!! an internal template mesh with `max(2,2*face_np)` cells: template cell `s` has all edges in
!! state `min(s,2)` (state 1: `lce>0`, state 2: `lce<0`) and all faces in state `s`. The FE
!! object is shallow-copied with its mesh pointer replaced, so the user's objects are not
!! modified.
!------------------------------------------------------------------------------
SUBROUTINE qcache_build_ref(self)
CLASS(oft_fem_qcache), INTENT(inout) :: self !< Basis cache
CLASS(oft_mesh), POINTER :: tmesh
CLASS(oft_fem_type), POINTER :: tfe
INTEGER(i4) :: i,iq,s,m,e,ns,np,k,j,row0,nd,d0
REAL(r8) :: gopu(3,4),cgopu(3,6),bmat(3,3),binv(3,3)
REAL(r8), ALLOCATABLE, DIMENSION(:) :: rop1
REAL(r8), ALLOCATABLE, DIMENSION(:,:) :: rop3,lt,ls
DO iq=1,3
  IF(self%q(iq)%xform<0)CYCLE
  ALLOCATE(self%q(iq)%ref(self%nrows,self%q(iq)%nlc,self%nqp))
  self%q(iq)%ref=0.d0
END DO
np=self%fe%mesh%face_np
ns=self%nstmax
!---Orientation template mesh
ALLOCATE(tmesh,MOLD=self%fe%mesh)
tmesh%type=self%fe%mesh%type
tmesh%cell_np=self%fe%mesh%cell_np
tmesh%cell_ne=self%fe%mesh%cell_ne
tmesh%cell_nf=self%fe%mesh%cell_nf
tmesh%face_np=self%fe%mesh%face_np
tmesh%nc=ns
tmesh%cell_ed=>self%fe%mesh%cell_ed
tmesh%cell_fc=>self%fe%mesh%cell_fc
ALLOCATE(tmesh%lce(tmesh%cell_ne,ns),tmesh%lcfo(tmesh%cell_nf,ns))
DO s=1,ns
  DO e=1,tmesh%cell_ne
    tmesh%lce(e,s)=e
    IF(s==2)tmesh%lce(e,s)=-e
  END DO
  tmesh%lcfo(:,s)=qcache_face_code(MIN(s,self%geom%nfs),np)
END DO
ALLOCATE(tfe,SOURCE=self%fe)
tfe%mesh=>tmesh
!---Evaluate on template cells (serial; reset orientation cache of standard evaluators)
oriented_cell=-1
ALLOCATE(rop1(self%nce),rop3(3,self%nce),lt(self%nce,6),ls(self%nce,3))
!---Unit logical frame: independent gop columns = identity, dependent column consistent
gopu=0.d0
DO k=1,3
  gopu(k,self%geom%gc(k))=1.d0
END DO
IF(self%geom%gc(1)==2)gopu(:,1)=-(gopu(:,2)+gopu(:,3)+gopu(:,4))
CALL oft_hcurl_get_cgops(gopu,cgopu)
DO k=1,3
  bmat(:,k)=cgopu(:,self%geom%hc(k))
END DO
CALL qcache_inv3(bmat,binv)
DO s=1,ns
  DO m=1,self%nqp
    DO iq=1,3
      IF(self%q(iq)%xform<0)CYCLE
      !---Logical components lt(:,1:nlc) in the folded frame (see qcache_geom_setup)
      SELECT CASE(self%q(iq)%xform)
        CASE(qc_xform_none)
          CALL qcache_eval_direct(tfe,self%basis,iq,s,self%geom%pts(:,m),gopu,cgopu,rop1,rop3,lt(:,1:1))
        CASE(qc_xform_gop)
          CALL qcache_eval_direct(tfe,self%basis,iq,s,self%geom%pts(:,m),gopu,cgopu,rop1,rop3,lt(:,1:3))
        CASE(qc_xform_cgop)
          CALL qcache_eval_direct(tfe,self%basis,iq,s,self%geom%pts(:,m),gopu,cgopu,rop1,rop3,ls)
          ! Coefficients in the basis cgopu(:,hc): lt = ls * binv^T
          DO k=1,3
            lt(:,k)=ls(:,1)*binv(k,1)+ls(:,2)*binv(k,2)+ls(:,3)*binv(k,3)
          END DO
      END SELECT
      !---Store blocks of entities whose state is represented by template cell s
      DO i=1,self%nent
        nd=self%ent_ndof(i)
        IF(nd==0)CYCLE
        IF(s>self%ent_nst(i))CYCLE
        row0=self%ent_row0(s,i)
        d0=self%ent_dof0(i)
        DO k=1,self%q(iq)%nlc
          DO j=1,nd
            self%q(iq)%ref(row0+j,k,m)=lt(d0+j,k)
          END DO
        END DO
      END DO
    END DO
  END DO
END DO
oriented_cell=-1
DEALLOCATE(rop1,rop3,lt,ls)
!---Transposed tables for the cell-batched kernels
DO iq=1,3
  IF(self%q(iq)%xform<0)CYCLE
  ALLOCATE(self%q(iq)%reft(self%q(iq)%nlc*self%nqp,self%nrows))
  DO m=1,self%nqp
    DO k=1,self%q(iq)%nlc
      DO j=1,self%nrows
        self%q(iq)%reft((m-1)*self%q(iq)%nlc+k,j)=self%q(iq)%ref(j,k,m)
      END DO
    END DO
  END DO
END DO
!---Free template objects (pointer components are shared and must not be freed)
NULLIFY(tfe%mesh)
DEALLOCATE(tfe)
DEALLOCATE(tmesh%lce,tmesh%lcfo)
NULLIFY(tmesh%cell_ed,tmesh%cell_fc)
DEALLOCATE(tmesh)
END SUBROUTINE qcache_build_ref
!------------------------------------------------------------------------------
!> Invert a 3x3 matrix
!------------------------------------------------------------------------------
PURE SUBROUTINE qcache_inv3(a,ainv)
REAL(r8), INTENT(in) :: a(3,3) !< Matrix
REAL(r8), INTENT(out) :: ainv(3,3) !< Inverse
REAL(r8) :: det
ainv(1,1)=a(2,2)*a(3,3)-a(2,3)*a(3,2)
ainv(1,2)=a(1,3)*a(3,2)-a(1,2)*a(3,3)
ainv(1,3)=a(1,2)*a(2,3)-a(1,3)*a(2,2)
ainv(2,1)=a(2,3)*a(3,1)-a(2,1)*a(3,3)
ainv(2,2)=a(1,1)*a(3,3)-a(1,3)*a(3,1)
ainv(2,3)=a(1,3)*a(2,1)-a(1,1)*a(2,3)
ainv(3,1)=a(2,1)*a(3,2)-a(2,2)*a(3,1)
ainv(3,2)=a(1,2)*a(3,1)-a(1,1)*a(3,2)
ainv(3,3)=a(1,1)*a(2,2)-a(1,2)*a(2,1)
det=a(1,1)*ainv(1,1)+a(1,2)*ainv(2,1)+a(1,3)*ainv(3,1)
ainv=ainv/det
END SUBROUTINE qcache_inv3
!------------------------------------------------------------------------------
!> Free basis cache (safe to call on an object that was never set up)
!------------------------------------------------------------------------------
SUBROUTINE fem_qcache_delete(self)
CLASS(oft_fem_qcache), INTENT(inout) :: self !< Basis cache
INTEGER(i4) :: iq
DO iq=1,3
  IF(ASSOCIATED(self%q(iq)%ref))DEALLOCATE(self%q(iq)%ref)
  IF(ASSOCIATED(self%q(iq)%reft))DEALLOCATE(self%q(iq)%reft)
  self%q(iq)%xform=-1
  self%q(iq)%nlc=0
  self%q(iq)%npc=0
END DO
IF(ASSOCIATED(self%ent_ndof))DEALLOCATE(self%ent_ndof)
IF(ASSOCIATED(self%ent_dof0))DEALLOCATE(self%ent_dof0)
IF(ASSOCIATED(self%ent_orient))DEALLOCATE(self%ent_orient)
IF(ASSOCIATED(self%ent_nst))DEALLOCATE(self%ent_nst)
IF(ASSOCIATED(self%ent_row0))DEALLOCATE(self%ent_row0)
IF(ASSOCIATED(self%xf_kind))DEALLOCATE(self%xf_kind)
IF(ASSOCIATED(self%xf_off))DEALLOCATE(self%xf_off)
IF(ASSOCIATED(self%xf_nreg))DEALLOCATE(self%xf_nreg)
IF(ASSOCIATED(self%xf_roff))DEALLOCATE(self%xf_roff)
IF(ASSOCIATED(self%xf_reg))DEALLOCATE(self%xf_reg)
IF(ASSOCIATED(self%xf_perm))DEALLOCATE(self%xf_perm)
IF(ASSOCIATED(self%xf_sgn))DEALLOCATE(self%xf_sgn)
IF(ASSOCIATED(self%xf_mat))DEALLOCATE(self%xf_mat)
self%nxf=0
self%xf_resid=0.d0
NULLIFY(self%fe,self%geom)
self%nce=0; self%nqp=0; self%nc=0; self%nrows=0; self%nent=0
END SUBROUTINE fem_qcache_delete
!------------------------------------------------------------------------------
